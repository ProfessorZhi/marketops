"""**安全层**：谁在调用，以及他允许做什么。

§2 的目标树把这一层与 ``domain/`` ``application/`` ``ports/`` ``adapters/``
``interfaces/`` 并列，而它不属于其中任何一层。理由是它跨越了两条边界：

* ``catalog.py`` / ``tokens.py`` / ``workspace.py`` 管的是**主体**（谁在调用、他有
  哪些角色、他准在哪个 Scene 里动手）；
* ``network.py`` / ``egress.py`` 管的是**目标**（前者的目标是地址 —— 这个 URL 允不
  允许被访问、这个监听地址允不允许被绑定；后者的目标是收件人 —— 这个地址准不准
  收我们的信）。两者判的东西不同（一个 URL、一个信箱），形状却逐条同构，
  而**它们是两道独立的闸**：``network`` 那一道在信写出来之前就拒掉一次抓取，
  ``egress`` 那一道在信发出去之前拒掉一个收件人。合并会让「我们只抓公开页面」
  与「我们只联系批准过的人」变成同一句话，而它们各自会被独立地违反。

`workspace.py` 与另外两个同属第一条而不是第三条：角色与工作区回答的是同一个句子
的两半 —— 「谁」与「在哪个范围内」。把范围那一半挂到对象层（每条读取各判一次），
会长出十五处可以漂移的判定，而漂移的那一处不报错，只是少了一次拒绝。

两者看似无关，其实是同一句话的两面：**不允许被信任的输入，不因为「服务内部
产生的」而自动可信**。主体来自 HTTP 头（不可信，要认证），URL 来自调用载荷
（不可信，要过判据）。把它们放进调用方各自的层里，会长出第二个副本 ——
浏览器抓取器与 HTTP 抓取器各实现一份 URL 判据，然后其中一份先被修好。

## 它不 import 任何一层

本包的五个模块只依赖标准库与 ``domain/``（异常、枚举与那个 id 判据）。它不 import
``adapters/``、不 import ``application/``、不 import ``mcp``。这个方向是刻意的：
``adapters/mcp_server/``（服务面）与 ``interfaces/mcp/``（入口）都依赖本包，而本包不知道 MCP 存在 —— 于是「权限判据」可以在
一个不装 MCP SDK 的进程里被单独测试，也可以在将来换掉 SDK 时不动一行。

## 这一层此前不存在，而它的缺席有代价

在 Phase C 之前，这个仓库里**没有任何地方**能回答「哪些 URL 允许被抓取」——
``adapters/http.py`` 收得下就发。那在单机实验里看不出问题（发起人是我），
而 MCP 落地之后 URL 的来源变成调用方传进来的字符串，「我们只抓公开页面」
就只是一句话。

判据现在是可执行的：``tests/test_network_policy.py``（判据本身）与
``tests/test_acquisition_target_policy.py``（判据真的接在抓取器上，且被拒绝的
那一跳**根本没有离开进程**）。按本仓的规矩，一条没有执行器的边界只是自觉。
"""

