#: 目录本体。``MappingProxyType``：运行期不可写。
#:
#: 「谁能调什么」若是运行期可写的一个 dict，任何一处「临时放行」都能改掉全局
#: 权限，而且不留痕。冻结它，让那件事必须走代码评审。
TOOL_CATALOG: Mapping[str, ToolSpec] = MappingProxyType(_TOOL_CATALOG)


def spec_for(name: str) -> ToolSpec | None:
    """按名字取一行；不在目录里返回 ``None``（不抛）。"""
    return TOOL_CATALOG.get(name)


def authorize(principal: Principal | None, name: str) -> ToolSpec:
    """判定一次调用。

    三种失败合成**一个** ``AuthorizationError``：没有主体、工具不在目录里、
    角色不允许。合成一条不是为了让错误信息含糊 —— 服务面对外返回的本来就
    必须是同一条（见 ``adapters/mcp_server/guard.py``）。在这里就分开，只会诱使
    调用方把理由透出去。

    返回 spec 而不是 ``None``/``True``：调用方几乎总是需要那个 ``phase``
    （好回答「这个工具还没实现」），让它在判定成功时顺手拿到，就不必再查一次表。
    """
    if principal is None:
        raise AuthorizationError(f"没有已认证的主体，拒绝调用 {name!r}")
    spec = TOOL_CATALOG.get(name)
    if spec is None:
        raise AuthorizationError(f"{name!r} 不在工具目录里")
    if not (principal.roles & spec.roles):
        raise AuthorizationError(
            f"主体 {principal.name!r}（角色 {sorted(r.value for r in principal.roles)}）"
            f"无权调用 {name!r}"
        )
    return spec


def visible_tools(principal: Principal | None) -> tuple[str, ...]:
    """这个主体在 ``tools/list`` 里应当看见的工具名，排序后返回。

    **看不见**与**调不动**是两件事，两件都要做。只做后者时，研究侧 worker
    仍然能列出 control 目录 —— 那既是一次信息泄漏（它知道了这套服务能做什么），
    也是一条把「不属于你的工具」与「不存在的工具」区分开的旁路。

    排序而不是按目录插入顺序：目录是 dict，插入顺序会随一次无关的改动而抖动，
    于是同一个主体的工具列表在两次调用之间变化。
    """
    if principal is None:
        return ()
    return tuple(sorted(name for name, spec in TOOL_CATALOG.items() if principal.roles & spec.roles))
