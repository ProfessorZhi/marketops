"""谁能调哪些工具（§7）。

## 权威在文档

工具的**清单**不是在这里创作的，而是两份文档里那些表的抄本 ——
``docs/MCP_SERVICE.md`` §2 / §3（那十五条，字面钉在 ``3744262af7…``）与
``docs/MCP_PRODUCT_LOOP.md`` §2（产品环那十五条）。一个字都不在这里发明。
``tests/test_security_catalog.py`` 把**各来源**读出来，断言它们名字的**并集**
与下面这份目录逐字相等，所以「代码少了一个工具」与「代码多了一个工具」都会红：
少了会静默降级（调用方拿到「工具不存在」，而没人知道那是遗漏还是设计），
多了会静默开出一条没人评审过的权限面。

为什么不是一份文档：``MCP_SERVICE.md`` 表头那句「future capabilities must not be
inserted into those tables as if already approved and registered」把那张表变成了
一份**历史记录**（在那个 revision 上注册了哪 15 条）。往里面加行，是让一句当时
为真的话变成假话，而且改的人不会意识到自己改的是它。多开一份文档、判据取并集，
被放宽的是「工具住在哪份文档」，不是「目录必须与代码一致」。

## 三种事实，刻意分开

* ``roles`` —— **谁**能调。这是权限，来自文档的目录归属。
* ``phase`` —— **什么时候有实现**。这是建设进度，不是权限。
* ``summary`` —— **做什么**。这是给人读的。

合成一个字段（比如「本阶段可用的工具」）会让「研究侧不能调 control 工具」与
「这个工具还没实现」在行为上长得一样，而它们的排查方向完全不同。

## 为什么权限是一个纯函数

``authorize`` 只吃 ``(Principal, 工具名)``，不吃调用载荷、不吃环境、不吃时钟。
主体从哪来是另一个模块的事（``tokens.py`` 从传输层来），本模块不关心 ——
这个分界让「拿模型自己填的字符串当认证」在本模块里**根本无法表达**：
函数签名里没有那个位置可放。
"""

