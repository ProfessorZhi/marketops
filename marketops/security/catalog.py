class Role(str, Enum):
    """服务面的三种调用方。

    取值的**粒度**是一条设计决定：角色少而稳定，胜过角色多而含义重叠。
    三个角色各对应一个真实存在的主体，而第三个的「它是谁」是写下来的：

    * ``CONTROLLER`` —— Claude Code。决定研究什么、经营哪个市场、读报告。
    * ``RESEARCHER`` —— 一个研究 worker。在一个被分配的作业里抓取与提交。
    * ``AUTHORIZER`` —— **一个人**，而不是一个代理：为这个市场承担「可以联系
      这些人」这件事的运营责任人。它的令牌只铸来登记授权记录，别的什么都做不了
      （目录里它唯一能调的工具是 ``authorize_wave``），因为这一格的全部价值就是
      **它不是一个代理能自己走到的位置**。

    ## 为什么授权要单独一个角色，而不是「controller 多一个工具」

    §6 逐字：「授权必须来自可信、独立授权的责任人，或受管授权记录；模型写下
    『我批准』、普通控制者自授一个角色、或者 ``send_authorized=true`` 都不产生
    授权」。**「独立」是这句话里唯一不能被代码之外的任何东西替代的一维** ——
    一条给 controller 的 ``authorize_wave`` 让「谁批准了」与「谁准备并发出去了」
    合成同一个主体，而那正是这句话要分开的东西。

    角色在这里是**能被强制的那一半**：controller 的令牌**调不动**
    ``authorize_wave``（``authorize`` 只看角色，不看名字、不看载荷），所以一个
    代理不能凭自己写下的一句话把一批信放出去。强制不了的那一半写在下面。

    ## 强制不了的那一半，写在这里而不是绕开

    代码分不出两个令牌是不是铸给了**同一个人**：环里的一条条目若同时带
    ``marketops:controller`` 与 ``marketops:authorizer``，两个角色就落在同一个
    主体上，而这一层看不出任何异常。可强制的是那一条的**书写**：``tokens.py``
    在装载环时拒绝同时带这两个角色的条目（第一个能说出「为什么不行」的地方），
    于是「让一个主体同时握住闸门的两半」必须是一次**改环文件**的动作，而不是
    一条可以被工具走出来的路径。

    两个令牌铸给同一个人这件事，代码永远挡不住 —— 它挡在流程里：铸
    ``authorizer`` 令牌是一次由人做的、有记录的动作。
    """

    CONTROLLER = "controller"
    RESEARCHER = "researcher"
    AUTHORIZER = "authorizer"

    @property
    def scope(self) -> str:
        """OAuth scope 字符串。

        带 ``marketops:`` 前缀：机器上不止一个服务在发 scope，不带命名空间的
        ``researcher`` 会在将来某天与另一个服务的同名 scope 互相授权。
        """
        return f"marketops:{self.value}"


#: scope 字符串 → 角色。由 :class:`Role` 派生，不手写。
SCOPES_BY_ROLE: Mapping[str, Role] = MappingProxyType({role.scope: role for role in Role})


def roles_from_scopes(scopes: object) -> frozenset[Role]:
    """把令牌里的 scope 列表翻成角色集合。

    不认识的 scope **不报错**，只是不给任何角色。这是刻意的失败关闭：
    令牌里写错一个 scope 的结果是「什么都调不动」（当场可见），而不是
    「照旧拥有原来的权限」（事后才发现）。令牌**文件**里的角色名拼错是
    另一件事，那一层直接拒绝装载 —— 见 ``tokens.py``。

    输入用 ``object`` 而不是 ``Iterable[str]``：这个值来自解码后的令牌声明，
    它可能是任何东西，而一个宽容的签名会让 ``roles_from_scopes("controller")``
    （一个字符串，逐字符迭代）静默地什么都不给。
    """
    if not isinstance(scopes, (list, tuple, set, frozenset)):
        return frozenset()
    granted = {SCOPES_BY_ROLE[scope] for scope in scopes if scope in SCOPES_BY_ROLE}
    return frozenset(granted)


@dataclass(frozen=True)
class Principal:
    """一个已被认证的调用方。

    ``roles`` 是 ``frozenset`` 而不是 ``set``：权限在运行期不可增长。
    一个可变的角色集合，配上任何一个「临时放行」，就是一次不留痕的扩权。

    ``name`` 是人读的标识（``claude-control`` / ``worker-3``）。它**不**参与
    授权判定 —— 判定只看角色。名字参与的是审计与 ``get_job`` 的归属显示。

    ``workspaces`` 是**范围**那一维，与 ``roles`` 是两件事、由两个函数判
    （``catalog.authorize`` 与 ``workspace.require_workspace``）：角色答「这个人
    准不准调这个工具」，工作区答「在那个工具里他准动哪个 Scene 的对象」。
    合成一个字段会让「研究侧不能调 control 工具」与「这条令牌不是给这个场景铸的」
    在行为上长得一样，而它们要改的东西一个是角色、一个是一次重铸。

    缺省是**空集**而不是「全部」：一个只填了角色的主体（测试里的
    ``Principal("w", frozenset({Role.RESEARCHER}))`` 就是这种）在范围上什么都
    没有，于是任何业务调用都会被拒。这个缺省是失败关闭的那一边 —— 另一边的
    缺省（「空 = 哪都能动」）会让忘填一格变成一次不留痕的放行。
    """

    name: str
    roles: frozenset[Role]
    workspaces: frozenset[str] = frozenset()


@dataclass(frozen=True)
class ToolSpec:
    """目录里的一行。"""

    name: str
    #: 能调用它的角色。空集合会被测试拒绝：谁都调不了的工具不该在目录里。
    roles: frozenset[Role]
    #: 建设阶段的字母，取自 :data:`PHASES`。**不是权限**，是「什么时候有实现」。
    phase: str
    summary: str


def _spec(name: str, roles: frozenset[Role], phase: str, summary: str) -> tuple[str, ToolSpec]:
    return name, ToolSpec(name=name, roles=roles, phase=phase, summary=summary)


