"""Run 记录 —— §B17 的存储契约。

返回值类型与 id 的推导都在 ``domain/run.py``（它们必须跨实现一致，所以不在任何
一个实现里）。实现有两份：``adapters/sqlite/runs.py``（跨进程，靠
``BEGIN IMMEDIATE``）与 ``adapters/memory.py``（测试替身）。两份跑同一份契约，
判据见 ``tests/test_run_contract.py``。

**跨实现不能漂移的裁定写在模块里，不写在实现里**：受理面的两条判据 ——
:func:`admission_refusal`（这份请求本身走不走得通）与 :func:`window_refusal`
（这条授权链是不是已经到了一条 stop）—— 都住在这里，两个实现都调用它们 —— 与
``ports/jobs.py`` 的 ``repin_refusal`` / ``settlement_outcome`` 同一条分工。
把判据抄进两个实现，分家的表现是其中一个**静默地受理**一个另一个拒绝的规格，
而「两个实现都通过」这句话就没有依据了。

那两条是**两条**而不是一条，理由不是它们判的东西不同（都是「这次能不能受理」），
是**它们要的输入不同**：前者只读规格与时刻，后者要读盘上这条链走到哪了。合成一条
的话，那个函数要么拿不到链的读数，要么凭空多一个只有一半调用会填的参数 —— 而后者
的形态是「填了才判、不填就跳过」，也就是 §B17 条件 4 那三个阈值里最容易被静默跳过
的那一格。两条判据各自收得下自己那一半的输入，次序在 :meth:`RunStore.admit`。

## 端口上**没有**的东西，逐条给理由

* **没有 ``list_runs``。** 与 ``ports/jobs.py`` 没有 ``list_jobs`` 是同一条纪律，
  而这里多一层理由：§B17 条件 3 要求 manual 的 Run 走完之后**保持 idle、绝不自行
  扩下一批**，而「下一批」正是从一个能列出全部 Run 的入口开始的。一个只被测试
  用到的列举入口，会让人以为有一个 Run 队列在那里等着被推进。
* **``chain_progress`` 在，而它不是那条禁令的反例。** §B17 条件 4 要的是一个横跨
  这条链所有轮的**累计**读法（「达到对象数/累计预算/截止时间任一 stop 后不创建下一
  Run」），而 ``get(run_id)`` 答不了它 —— 一条链上一轮的时候没有人看得出来。所以
  这里有一个读，但它的形状是**计入与计数**：没有 ``run_id``、没有次序、没有「下一轮
  是谁」，只有 :class:`ChainProgress` 那五个字段。判据是它**拿不开下一轮** ——
  一个拿它去建 Run 的实现，要自己发明一个 run_id 与一个幂等键，而两者都由调用方给
  （``domain/run.py::run_id`` 逐字：「服务端一旦能自己造一个键，它就能造出第二个
  Run，而『自行扩下一批』正是从那里开始的」）。
* **没有 ``lease`` / ``release``。** 租约住在 ``ports/jobs.py``：Run 不重造执行器
  （计划原话是「保留已受理 Run 内部自动续跑」，那件事由 ``ContinuationController``
  做），它圈范围、定信封、记账。Run 这一层再加一套租约，会让「谁在跑这一轮」有
  两个真相来源。
* **``stop`` 在这里，且带着 ``RunDelta``。** 理由与 ``settle`` 带着 ``Settlement``
  一起进完全一样：「这一轮停了吗」与「它产出了什么」必须在**同一个写事务**里发生。
  分成两步（先写结局、再补产出）会造出一个「已结束但产出还没写」的窗口，而那个窗口
  里读的人无法区分「它什么都没产出」与「产出丢了」。
"""

