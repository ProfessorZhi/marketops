@dataclass(frozen=True)
class ChainProgress:
    """一条授权链**已经走了多远** —— 不是「这条链上有哪几轮」。

    ## 它为什么不是一份 Run 列表

    模块 docstring 逐字写着本端口**没有** ``list_runs``，理由是 §B17 条件 3 那句
    「绝不自行扩下一批」：「一个只被测试用到的列举入口，会让人以为有一个 Run 队列
    在那里等着被推进」。条款 4 确实要一个「横跨这条链所有轮」的读法，所以那个读法
    必须是**同一件事的另一种形状**，不是把 ``list_runs`` 加回来：

    * 没有 ``run_id``。有 id 就能顺手 ``get`` 出这一行、顺手在它后面排下一轮 ——
      而这一层要回答的只有「累计走到哪了」，不是「这一轮是谁」。
    * 没有次序。「这条链上最早/最近的一轮」是队列的语汇；本读数**按定义与次序无关**
      （对象数、花掉多少、有没有一轮在跑，都不随盘上行序变）。
    * 没有「还差多少才到下一轮」。三个阈值要与窗口一起看才谈得上「到没到」，而窗口
      不在这一层（它在 ``RunSpec`` 上）。

    字段全是**计数与标识**，于是「拿它去开下一轮」在结构上写不出来。

    ## ``objects`` 数的是**处置过的对象**，去重

    ``RunDelta.effects`` 的键，跨这条链上**每一条已经结束的轮**取并集。三个决定：

    * **全部九格都算**，不只 ``discovered`` / ``promoted``。理由有两条，任何一条都够：
      只数新增的话，一条只做维护的链（每轮全部 ``unchanged``）会被读成「一个对象都
      没走」而**永远不触发** —— 而它恰恰是每轮全量重走、最需要上限的那种链；而
      ``held`` / ``blocked`` / ``excluded`` 也确实是这一轮**看过**的对象（「走过」
      的字面就是处置过一行）。
    * **去重**。一个对象是一个身份（``PoolEffect.key``），走过三次仍是一个对象。
      重复走同一批对象是**成本**问题，那一条归窗口的 ``budget`` 管 —— 两条阈值各有
      各的主语，重合的那一天它们会互相掩盖。
    * **只算已经结束的轮**。一轮还在跑的时候它的 ``delta`` 是 ``None``（``Run`` 的
      三格同时有或同时无）—— 没有产出就没有走过什么可数。它**不是被忽略**：它进
      :attr:`open_runs`，而受理面对非零的 ``open_runs`` 有自己的处置。

    ## ``reservations`` 还是 id，不是金额

    与 ``RunDelta.usage`` 逐字同一条理由（那里的类文档讲全了）：「金额只有一个权威
    （``ports/budget.py`` 的那一处 ``SUM``），在回执里再抄一个数就是第二个答案」。
    所以这一格只把**哪几笔**带出来，求和发生在能读到账本的那一层。

    ## ``open_runs`` 为什么在这里

    §B17 `:247` 逐字是「按累计对象数/预算/截止时间/stop conditions 创建**后续** Run」，
    而 `:239` 说 Workstream「一轮一轮长大」。「后续」是「上一轮之后」，不是「同时」——
    所以「这条链上还有一轮没结束」是受理面**判得出**的一件事，而它需要一个计数。
    它是同一次查询的副产物，不是新的一处状态。
    """

    #: 这条链的标识（``AuthorizationWindow.digest``）。
    window_digest: str
    #: 这条链上**已经结束**的轮数。
    runs: int
    #: 这条链上**还没有结束**的轮数。见类文档末节。
    open_runs: int
    #: 这些轮处置过的业务键，**去重后**的个数。见类文档第二节。
    objects: int
    #: 这些轮记下的预留 id，去重后按字典序。见类文档第三节。
    reservations: tuple[str, ...]


def progress_of(
    workspace: str,
    window_digest: str,
    runs: Iterable[Run],
) -> ChainProgress:
    """把一批 Run 折成「这条链已经走了多远」—— **两个实现共用的那一份**。

    与 :func:`admission_refusal` 同一条分工（模块 docstring 第二节）：跨实现不能漂移
    的裁定写在模块里。两个实现各自只做「**取候选行**」（按 ``workspace`` 那一列，
    主存那份可以走既有的 ``research_run_by_workspace`` 索引），筛选与折叠全在这里。

    ## 两个筛选条件都在这里，不在实现里

    ``workspace`` 与 ``window_digest`` 都在这一个函数里比。实现**可以**多取（比如
    不写 ``WHERE`` 全表取回来），这个函数会把不属于这条链的行丢掉 —— 反过来不行：
    一个把筛选写进实现的那一份，与这一份在「窗口摘要相等」这件事上分别演进的那天，
    两个实现会对同一条链给出不同的累计，而受理面拿到哪一个取决于用了哪个 store。
    这正是 ``ports/jobs.py`` 那一段要防的形态。

    ## 传进来的行不必有序，也不必已筛选

    「不必有序」是刻意的：读数与次序无关（见 :class:`ChainProgress`），所以它不要求
    调用方先排一遍 —— 一个要求有序的读数会让两个实现各排一次，而排序口径的差异
    （按 ``created_at``？按 ``run_id``？）在这里是看不出来的。

    ``run.spec.window`` 为 ``None`` 的行（``manual`` / ``watch``）自然落选：它们没有
    窗口，也就**不属于任何一条授权链**。
    """
    ended: list[Run] = []
    open_runs = 0
    keys: set[str] = set()
    reservations: set[str] = set()
    for run in runs:
        window = run.spec.window
        if window is None or window.digest != window_digest:
            continue
        if run.spec.workspace != workspace:
            continue
        if not run.is_stopped:
            open_runs += 1
            continue
        ended.append(run)
        delta = run.delta
        if delta is None:  # pragma: no cover - Run 的三格同时有或同时无
            continue
        keys.update(effect.key for effect in delta.effects)
        reservations.update(delta.usage)
    return ChainProgress(
        window_digest=window_digest,
        runs=len(ended),
        open_runs=open_runs,
        objects=len(keys),
        reservations=tuple(sorted(reservations)),
    )


def admission_refusal(spec: RunSpec, *, at: datetime) -> str:
    """这次受理**今天走不通**的理由；走得通时返回空串。

    它是两个实现共用的那一份判据（见模块 docstring）。返回字符串而不是抛异常，
    与 ``ports/jobs.py::repin_refusal`` 同款：实现要决定把这个理由放在哪一种拒绝里，
    而判据本身只回答「走不走得通」。

    ## 这里判的只有「请求本身说得通吗」，链的状态不在这里

    e2 之前，这一条对**每一个**非 ``manual`` 的模式都给同一句话（逐字：「它的授权
    窗口有形状了……但还没有一处读过它」），而且它自己写明「这与这一份规格有没有带
    窗口无关」。**那句话当时是对的，因为窗口确实没有读者。** e2 把那句话拆成了两
    句，两句的处置不同：

    ==================================================  ==================================
    输入                                                  谁说
    ==================================================  ==================================
    ``watch`` 而主体上**没有**到期/信号                   :func:`application.run_admission.admit_run`
                                                        （切片 f —— 它**要读盘**，见下）
    ``bounded_auto`` **没有**窗口                       这里 —— 「这一次请求没有写下窗口」
    ``bounded_auto`` 有窗口，而这条链到了阈值           :func:`window_refusal`
    ==================================================  ==================================

    拆开的理由不是把一句话分成两句好看，是**那两句要的输入不同**：第三句要读盘上这
    条链走到哪了，而这一层拿不到那个读数（它是存储的事，而且要在写事务里读）。
    两句合在一起的那天，只有一种写法走得通 —— 要么这里看不见链、于是永远答
    「这一次请求没有写下窗口」，要么这里凭空多一个参数。**先触发的那一处就是全部**：
    e1 的变异 E11 实测的就是这个形态（域层先炸，端口那句一个字都到不了人眼前）。

    ## ``watch`` 那句话在切片 f 之后**换了住处**，而理由是同一个

    e2c 之前这一层对 ``watch`` 说过一句话：它的来源（到期/信号/日程）**还没有生产者**
    —— 今天没有一处会因为一个对象到期而提交一次受理。切片 f 把那个来源接上了，所以
    **那句话不再成立**，它被删掉了，转成一条**真的核验**。

    取回那一句要用的针是它自己的一截尾巴，不是它的主干：
    ``git log -S "没人问它" -- marketops/ports/runs.py``（``5ebc789`` 写进去、切片 f
    那一次删掉）。主干那句「它的来源是 Watch 的」**不能用** —— 本节上面又逐字引了它
    一次，于是它在 ``-S`` 眼里「次数没变」，那一次删除不会被列出来。

    新那一句没有搬进这个函数，而这不是省事：它要**读维护账**（那份主体上有没有到期
    的格子），而本函数收不到存储、也不该收 —— 上面那一节「两条都只读 ``spec`` 与
    ``at``」正是它能被调在写事务**之外**的原因。所以它落在**第三句那一类**里
    （:func:`window_refusal` 与 :func:`application.run_admission.admit_run`），也就是
    「读盘、由实现在事务里调」的那一类。这是同一条分工的第三次应用，不是例外。

    ## 「没有窗口的自动模式受理不了」这句话的理由换过两次，两次都更准

    这句话本身一直是成立的，变的是**它点名的缺的是哪一样**：

    * **e1 时**：窗口已经**有形状了**（``domain/run.py::AuthorizationWindow`` 是
      e1 那一提交带进来的），缺的是**读者** —— 没有一处读过它，「这条链累计走到
      哪了、该不该开下一轮」那个判据当时不存在。所以拒词逐字是「它的授权窗口
      **有形状了**……但还没有一处读过它」。
    * **e2 时**：形状与读者都有了，`submit_run` 却恒传 ``None``，于是拒词改点**生产
      者**（「没有一处会写下它」）。
    * **e2c 之后**：`submit_run` 收得下窗口了（第七个参数），于是「没有生产者」这句话
      不再成立，拒词回到**这一份请求**上 —— 它没有写下窗口。

    三次都不是改措辞：每一次都是那句判断所依据的事实变了，而拒词跟着换。这里留一
    段历史是因为下一次有人读到「没有窗口就拒」时，最自然的猜测是「所以是不能带窗
    口」—— 而真相是**能带**，只是没带的那一份与「没有人授权过」在能做的事上完全
    一样（``domain/run.py::AuthorizationWindow`` 逐字：「只有显式授权窗口存在时」）。

    窗口**由谁签**不在这里判：那是身份/授权层的事（B01/B02），本函数只答「这一份规
    格今天走不走得通」。一份由调用方提交的窗口是**显式**的（它写在 ``RunSpec`` 里，
    与「由 mode 隐含」相对），而「谁有权提交它」是另一个问题 —— 见 ``submit_run``
    那一格 ``window`` 的 docstring。

    ## 第二条：截止时刻不在将来

    一个从出生就过期的 Run，它的第一个动作就是发现自己在截止之后 —— 那段余量是负
    的，而按阈值停的那套逻辑会把「没时间了」读成「跑完了」。

    ## 两条都只读 ``spec`` 与 ``at``

    这是这个函数能在写事务**之外**被调用的原因（两个实现都在开事务之前调它）：它答
    的是「这份请求今天走不走得通」，而那个答案不随盘上的行变。链那一条做不到这一点，
    所以它在事务里、在这一函数之后 —— 顺序与理由见 :func:`window_refusal` 与
    :meth:`RunStore.admit`。

    ``at`` 从外面进来，不在这里读时钟：上面那条判据比的是「现在」，而一个读自己
    时钟的判据在测试里只能靠等待来触发。
    """
    if spec.execution_mode is ExecutionMode.BOUNDED_AUTO and spec.window is None:
        return (
            "执行模式 'bounded_auto' 没有带授权窗口，而这一份授权**要写下来**："
            "「这条链最多走多少个对象、花多少、到什么时候为止」是一份要写下来的授权"
            "（``domain/run.py::AuthorizationWindow``，三项都是必填）。\n"
            "没有窗口的自动模式与「没有人授权过」在能做的事上完全一样 —— 它会在记录里"
            "写下「这一轮之后可以自己接下一轮」，而那两个阈值一个都不存在。\n"
            "这是一条**拒绝**，不是一次受理：拒绝要比假装受理诚实。\n"
            "处置是把窗口写进这一次请求（``submit_run`` 的 ``window`` 那一格："
            "``max_objects`` / ``budget`` / ``not_after``），或者把模式改回 'manual' —— "
            "后者说的是「这一轮跑完就停在那儿」，不需要任何人签任何东西。"
        )
    if spec.cutoff <= at:
        return (
            f"截止时刻 {spec.cutoff.isoformat()} 不在将来（受理时刻是 {at.isoformat()}）。\n"
            "一个从出生就过期的 Run 会把「没时间了」按阈值那套逻辑读成「跑完了」—— "
            "而那两件事的处置相反：前者要人去把窗口挪开，后者只有一句话『做完了』。"
        )
    return ""


def window_refusal(
    spec: RunSpec,
    *,
    progress: ChainProgress,
    spent: Mapping[BudgetLine, int] | None,
) -> str:
    """这条授权链**已经到了一条 stop** 的理由；没到就返回空串。

    权威是 §B17 条件 4 逐字：「``bounded_auto`` 在达到对象数/累计预算/截止时间**任一**
    stop 后不创建下一 Run；重放 trigger 不重复创建。」「任一」是这一条的形状：三条
    理由各自说自己的话，**不合成一条「到上限了」** —— 因为三条处置不同（下面逐条写）。

    与 :func:`admission_refusal` 同一条分工（判据一份、两个实现共用、返回字符串而不
    抛异常），但它**要读盘**，所以它由实现在**写事务里**调用（见 :meth:`RunStore.admit`
    的顺序一段）。这是它与上面那个函数唯一的结构差别，而那一条差别是必须的。

    它**不读时钟，也没有 ``at`` 参数** —— 这一点不是省一个参数，见下面那一节。

    ## 它只在有窗口时说话

    ``spec.window is None`` ⇒ 返回空串。理由：「链走到哪了」这句话对一条没有窗口的
    规格**没有主语** —— 一个 ``manual`` Run 不属于任何一条授权链（
    ``progress_of`` 逐字：「``run.spec.window`` 为 ``None`` 的行自然落选」）。
    没有窗口的 ``bounded_auto`` 由 :func:`admission_refusal` 拒，不在这里。

    ## ``progress`` 必须是**这条链**的读数

    ``progress.window_digest`` 与 ``spec.window.digest`` 不等 ⇒ 拒。这不是洁癖：一个
    读错了链的 ``progress`` 会给出**一个看起来完全正常的数**（对象数、轮数都有），
    于是受理面会拿另一条链的累计去判这一条 —— 而两个方向都错得难看出来（另一条链
    走得多 ⇒ 这一条被凭空卡住；走得少 ⇒ 这一条被凭空放行）。这个不等的形态只可能
    来自调用点写错，而它会**留下一条说得出话的拒绝**，不会静默过去。

    ## 条件 4 的第三个阈值（截止时间）**不在这里** —— 这一格是本片实测出来的

    §B17 条件 4 写的是三个 stop，而这里只有两条（对象数、累计预算）。第三条**已经由
    域层承担**，理由是两条已经存在的判定把它们串起来了：

    * ``RunSpec._window_agrees_with_the_rest`` 逐字拒绝 ``window.not_after < cutoff``
      ——「一个截止晚于窗口的 Run，会在授权已经过期之后还在跑」；
    * :func:`admission_refusal` 拒绝 ``cutoff <= at`` ——「一个从出生就过期的 Run」。

    两条合起来是 ``at < cutoff <= not_after``，也就是 ``at < not_after``：**任何一份
    走得通受理面的规格，它的窗口都还没到期。** 所以这里再写一句 ``window.not_after < at``
    是一条**永远不触发**的分支 —— 同一句话的第二份实现，而这一份连红都不会红。它就是
    本模块 docstring 第一条禁令（「判据只有一处出处」）要防的东西，只不过这次那份
    副本永远不会漂移得看得见。

    本函数因此**不收 ``at``**：一个收下时刻却不比它的参数，会让下一个读的人以为
    「窗口到期是这里判的」，而那一句话的出处其实在域层。**窗口的 ``not_after`` 不是
    没有读者** —— 它的读者是域层那条跨格校验器，而那条校验器的产物是「本轮 cutoff
    的上界」，受理面读的是那个上界。这一条由
    ``tests/test_run_window_admission.py::test_an_admitted_auto_run_always_starts_before_its_window_ends``
    钉住（判据的形态是**蕴含**，不是再写一遍那条校验器）。

    ## 四条的次序，以及为什么是这个次序

    下面四条里前两条不是 stop（一条是调用点写错的回执、一条是链还在走的回执），
    后两条才是条件 4 那两个阈值 —— 而它们在同一个函数里，因为受理面只需要知道
    「走不走得通」，不需要知道是哪一类理由。

    1. **累计读数是另一条链的**（``progress.window_digest`` 不等）。排第一是因为
       它不是一条 stop，是**这一次调用本身说不通**：后面三条都拿 ``progress`` 做
       判据，而一份错的读数会让那三条各自给出一个错的答案。处置是修调用点。
    2. **这条链上还有一轮没结束**（``open_runs > 0``）。依据是 §B17 `:247` 的
       「创建**后续** Run」与 `:239` 的「一轮一轮长大」：后续是「上一轮之后」，不是
       「同时」。处置：等那一轮结束 —— 而「它结束了吗」在 ``get(run_id)`` 上。
       这一条也是**唯一一条在并发下有意义**的：它在写事务里读，所以两个同时提交的
       自动受理里，后一个会看见前一个刚插进去的那一行。
    3. **对象数走到了**（``objects >= max_objects``）。口径见 :class:`ChainProgress`
       第二节。处置：这条链已经覆盖到它被授权的广度，要接着走是**一次新的授权**。
       它排在预算之前，因为它的读数是**盘上的行**（一定读得到），而预算那一条的读数
       要一份账本（读不到就要拒）—— 一条一定读得到的判据先答，能让「同时越过了两条
       阈值」这件事在报告上落到那条不需要额外接线的原因上。
    4. **累计预算走到了**（逐科目 ``spent[line] >= ceiling``）。这一格的读数是账本，
       不在 Run 记录里（:attr:`ChainProgress.reservations` 那一节讲全了）。``spent is
       None`` ⇒ **拒**，不是跳过：少了这一条，「没有账本读数」与「账本说没花」在受理面
       上同形，而两者处置相反（一个去接账本，一个可以继续）—— 与 ``RunDelta`` 那句
       「算不出来就抛，不返回 0」是同一条纪律，只是主语换成了这一格。
    """
    window = spec.window
    if window is None:
        return ""
    if progress.window_digest != window.digest:
        return (
            f"受理面拿到的累计读数是**另一条链**的：读数上的窗口摘要是 "
            f"{progress.window_digest}，而这一份规格的窗口摘要是 {window.digest}。\n"
            "这不是洁癖：一个读错了链的读数会给出一个看起来完全正常的数（轮数、对象数"
            "都有），于是这一条链会拿着另一条链的累计去判 —— 走得多就被凭空卡住、走得"
            "少就被凭空放行，而两个方向在报告上都看不出来。\n"
            "处置是修调用点：读数要用 ``chain_progress(workspace=..., "
            "window_digest=spec.window.digest)`` 读。"
        )
    if progress.open_runs:
        return (
            f"这条链上还有 {progress.open_runs} 轮没有结束。\n"
            "§B17 逐字是「创建**后续** Run」，而 Workstream「一轮一轮长大」—— 后续是"
            "「上一轮之后」，不是「同时」。同时开两轮会让这条链的累计（对象数、预算）"
            "在两次受理里各读到一个**还没算上对方**的数，于是两个都过、合起来超。\n"
            "处置是等那一轮结束（``get_run(run_id)`` 答得了「它停没停」）。"
        )
    if progress.objects >= window.max_objects:
        return (
            f"这条链已经处置过 {progress.objects} 个对象，达到了它的授权窗口"
            f"（{window.max_objects} 个）。\n"
            "口径是**去重后的业务键**（见 ChainProgress）：一个对象走过两次仍是一个"
            "对象 —— 重复走同一批对象是成本问题，那一条归窗口的 budget 管。\n"
            "处置是再要一次授权：这条链已经覆盖到它被允许的广度。"
        )
    if spent is None:
        return (
            "这条链的累计预算读不到：受理面没有拿到账本读数。\n"
            "窗口的三个阈值里，对象数与截止时间能从 Run 记录读出来，预算不能 —— "
            "金额只有一个权威（``ports/budget.py`` 的那一处 ``SUM``），而 Run 记录"
            "读不到它。\n"
            "**这一条是拒，不是跳过**：「没有账本读数」与「账本说没花」在受理面上同形，"
            "而两者处置相反（一个去接账本，一个可以继续）。与 ``RunDelta`` 那句「算不"
            "出来就抛，不返回 0」是同一条纪律。"
        )
    over = sorted(
        f"{line.value}（已 {spent.get(line, 0)}、窗口 {ceiling}）"
        for line, ceiling in ((one.line, one.ceiling) for one in window.budget)
        if spent.get(line, 0) >= ceiling
    )
    if over:
        return (
            f"这条链的累计预算走到了窗口上限：{over}。\n"
            "读数是账本（``ChainProgress.reservations`` 逐笔求和），不是这一轮的"
            "信封 —— 信封说的是「这一次允许用多少」，窗口说的是「这条链一共允许用"
            "多少」，两者都在。\n"
            "处置是再要一次授权：这一条链的预算用完了。"
        )
    return ""


def ending_refusal(status: RunStatus, delta: RunDelta) -> str:
    """用这份 Delta 以这个结局结束这一轮**今天走不通**的理由；走得通时返回空串。

    与 :func:`admission_refusal` 同一条分工（判据一份、两个实现共用、返回字符串而
    不是抛异常）。

    ## 只有一条理由：``COMPLETED`` 不许配一份每一格都空的 Delta

    §B17 条件 2 逐字要求「**合法零新增仍能以 unchanged/held/blocked 结束**」——
    注意那句话要求的是**零新增**有个归宿，不是**零产出**可以不写。「这一轮对象全
    走过了、结论不变」是一句话，它必须写下来（就是那一批 ``unchanged`` /
    ``held`` / ``blocked`` 的处置行）；而一个 ``COMPLETED`` 配一份两袖清风的回执，
    在报告上与「压根没跑」长得一样。

    所以这条判据**不**要求有任何新增：``effects`` 全是 ``UNCHANGED``、甚至只有
    ``routes`` / ``evidence`` 而没有一条池子处置，都是合法的 ``COMPLETED``。

    ``PARTIAL`` 与 ``FAILED`` 不受这条管：一轮在跑起来之前就断掉，产出确实是零，
    而要求它编点什么出来才是伪造。它与 ``COMPLETED`` 的区别正是那句结局词本身。

    **报文里不写「几格」。** 它从前写的是「八格全空」，而 ``RunDelta`` 的格数是会变的
    （B24 的 ``actions`` 那一格就是第九格）—— 一个写在拒词里的计数，在格子增加的那天
    会变成一句错话，而它印在一份要人照着重做的话里。判据本身由 ``delta.is_empty``
    回答，那一格数的是**每一格**。
    """
    if status is RunStatus.COMPLETED and delta.is_empty:
        return (
            f"结局 {status.value!r} 不能配一份**每一格都空**的 Delta。\n"
            "「这一轮走完了、什么都没变」是一句要有归宿的话：它写成那一批 "
            "unchanged / held / blocked 的处置行，才与「压根没跑」在报告上分得开。\n"
            "零新增是合法的（§B17 条件 2 要的正是它），零产出不是 completed 的形态 —— "
            "一轮在跑起来之前就断掉，它的结局词是 partial 或 failed。"
        )
    return ""


def stopping_outcome(status: RunStatus, delta: RunDelta) -> str:
    """一套结局与产出的**指纹**，两个实现比对重放时用同一个 —— 所以它住在这里。

    与 ``ports/jobs.py::settlement_outcome`` 同形同一件事（那边把理由讲全了：
    「两个实现比对重发时用同一个，所以它住在这里」）。

    **两半都必须进。** 只比产出，一份换了结局词的重发会被当成幂等接受 —— 于是
    「同一轮以两种结局结束过」这件事在存储层看不出来。只比结局词，一份换了产出的
    重发会被当成冲突 —— 而同一轮被重放时拿到的是同一份产出，那必须幂等。

    比的是**指纹**而不是两个模型：模型相等依赖 ``__eq__`` 的实现，而「怎么算同一套
    结局」是这一层的定义。两个实现各写一次的时候，分家的形态是其中一个接受了另一个
    拒绝的重放 —— 而两边都返回成功。
    """
    return f"{status.value}{SEP}{sha256_text(delta.model_dump_json())}"


def unknown_run_refusal(run_id: str) -> str:
    """``run_id`` 指不到任何一轮时的理由。与 ``admission_refusal`` 同一条分工
    （返回字符串而不是抛，实现决定把它放进哪一种拒绝里）。

    它单列出来，是因为这句话必须**逐字**出现在两个实现里：一个把「没有这一轮」
    写成「这一轮已经结束了」的实现，会把一次写错 id 读成一次重放。
    """
    return (
        f"没有这一轮 Run：{run_id}。\n"
        "这个 id 是**本层自己发出去的**（``domain/run.py::run_id``），所以拿不到它只有"
        "两种可能：这一次受理从来没有成功过，或者这个 id 根本不是 Run 的 id（本仓另有"
        "一个同名的记账标签 ``_derived_run_id()``，形状是 ``run-<时刻>``，它指不到"
        "这里）。\n"
        "两种情况都不该被当成「已经结束了」—— 那会把一次写错 id 读成一次重放。"
    )


def fold_ledger_refusal(run_id: str, *, run_exists: bool) -> str:
    """折入账**读不出来**时的理由。与 :func:`unknown_run_refusal` 同一条分工
    （返回字符串而不是抛，实现决定把它放进哪一种拒绝里）。

    它单列出来，理由与上面那一条逐字相同：这句话必须**逐字**出现在两个实现里 ——
    一份把它写成「这一轮一行都没折」的实现，正是 §B17 条件 2 要关掉的那条假账。

    ``run_exists`` 把两种成因分开说，因为它们的**下一步不同**：这一轮不在册，是
    一次拿错了 id（或者一次没做成的受理）；这一轮在册而账本不在，只可能是库被动过
    或者来自一个还没有账本的版本 —— 那要去查库，不是去查调用方。两种都**不返回
    零行**：把读不出来读成空账，恰好就是那条假账。
    """
    if not run_exists:
        return (
            f"没有这一轮 Run：{run_id}，所以也读不到它的折入账。\n"
            "**这不是「这一轮一行都没折」。** 零折入是一份**存在且为空**的账给出的"
            "读数，而它由受理当场写下（``RunStore.admit``）—— 所以「读不到」与「是空的」"
            "是两件事，处置相反：前者要停下来查，后者照常停表。\n"
            "按零处理会让「折了却没记」与「什么都没折」在账上同形，而池子已经变大了。"
        )
    return (
        f"Run {run_id} 在册，但它的折入账不在。\n"
        "受理会在**写这一行的同一个事务里**给每一轮开一份空账（``RunStore.admit``），"
        "所以这个状态**由写路径构造不出来**。它只可能来自两处：有人在库外动过手，"
        "或者这个库来自一个还没有折入账的版本。\n"
        "**不按零折入读。** 那一读会让「折了却没记」在账上长成「什么都没折」，而两者"
        "的处置相反 —— 池子变大了，账却是平的。"
    )


def fold_after_end_refusal(run_id: str, *, stop_reason: str) -> str:
    """往一轮**已经结束**的 Run 上记折入时的理由。与上面两条同一条分工。

    这一条挡的是时序：折入是**跑这一轮的过程中**发生的事，而结束那一刻的账正是按
    「到那时为止折了什么」结的。结束之后再记一笔，那一笔既不在这份账里，也不在任何
    一份账里 —— 它只是让下一次读这一行的账多出一笔，而**没有人会再核对它**
    （``close_run`` 已经跑过了）。

    与 :func:`unknown_run_refusal` 那一处同一个错误的两种写法：把「这一轮已经结束了」
    读成「这一轮不存在」会让人去查受理记录，而问题在时序上。
    """
    return (
        f"Run {run_id} 已经结束了（{stop_reason}），不能再往它上面记折入。\n"
        "一轮结束那一刻的账是按「到那时为止折了什么」结的（``close_run`` 读的就是这份"
        "账）。结束之后再落一笔，这一笔不在那一份账里 —— 而它也不会被任何一次核对看见，"
        "因为那一轮不会再结束第二次。\n"
        "它只可能来自一次时序错乱：折入属于**跑这一轮的过程中**。如果这一笔本该记在"
        "某一轮上，那一轮还在跑吗？如果它压根不属于任何一轮，那 ``fold`` 应当留空 —— "
        "「这一行不属于任何一轮」是一个被声明出来的事实，不是一句要猜的话。"
    )


def fold_replay_conflict(
    run_id: str,
    receipt_id: str,
    ordinal: int,
    *,
    recorded: str,
    incoming: str,
) -> str:
    """重放键撞上**另一个句柄**时的理由。与上面三条同一条分工。

    这一条不是「重放」：重放的判据是同一个 ``(run_id, receipt_id, ordinal)`` 配**同一个**
    句柄，而那时它一个字节都不写（见 ``RunStore.folds_of`` 与两个实现）。配了另一个
    句柄是完整性冲突 —— 要么这一笔被记了两次而第二次折的是别的行，要么有人动了库。
    两种都不该被静默接受：接受会让「这一轮折了什么」有两个答案，而账本的全部价值就是
    它只有一个。
    """
    return (
        f"同一份回执的同一行（Run {run_id}，回执 {receipt_id!r} 第 {ordinal} 行）"
        f"折进了另一个句柄：账上是 {recorded}，这一次是 {incoming}。\n"
        "账本按 (run_id, receipt_id, ordinal) 判重放，而不是按句柄 —— 一份回执里两行"
        "可以折进**同一块**场地（没有来源编号、名字与地点又相同的那两行），所以句柄"
        "不能当那个键。\n"
        "同一个键配两个句柄只可能来自两处：有人动了库，或者一条回执被换了内容却留着"
        "同一个 receipt_id。"
    )


class RunStore(ABC):
    """持久 Run 记录。

    参数一律关键字化（除规格本身），理由与 ``JobStore`` 相同：``admit`` 的实参里
    每一个都是语义上必填的，位置传参会让「规格」与「它的摘要」在调用点上长得一样，
    而这两样搞反了不会报错 —— 只会给一份规格配上一个别的规格的摘要，于是冲突检查
    开始漏报。
    """

    # ------------------------------------------------------------------
    # 受理（§B17 条件 1 的前提）
    # ------------------------------------------------------------------
    @abstractmethod
    def admit(
        self,
        spec: RunSpec,
        *,
        spec_sha256: str,
        at: datetime,
        spent: Mapping[BudgetLine, int] | None = None,
    ) -> Run:
        """受理一次增量。**幂等**：同一个 ``(workspace, key)`` 拿回同一个 Run。

        **受理不是执行。** 这个方法只写下一行 Run（信封、截止、策略版本都在里面），
        它不派发任何东西、不碰预算、不创建 work item —— 那些是作业层的事，而它们
        必须由一个已经存在的 Run 记账，不是在这一步顺手做掉。

        ## 三处判定的**次序**，以及每一处为什么在那里

        1. **:func:`admission_refusal`** —— 在写事务**之外**、读盘**之前**。它答的是
           「这份请求今天走不走得通」，而那个答案不随盘上的行变（它只读 ``spec`` 与
           ``at``）。放在事务外还有一个好处：一份**永远**受理不了的规格（比如一个
           ``watch``）连写锁都不去争。
        2. **重放检查** —— 写事务**之内**、:func:`window_refusal` **之前**。
           ``get(rid)`` 命中就返回那一行，**不再问窗口**。这一条是次序里最要紧的：
           重放那条路径的承诺是「拿回同一行」（上面那句「幂等」），而链的累计是**会
           变**的 —— 一条链走到 stop 之后，同一份规格的**重发**必须照旧拿回那一行，
           不能变成一次拒绝。受理面若在这里答「达到 stop 了」，调用方会把一个**已经
           被受理过**的请求读成「这次没被受理」，而盘上那一行还在。
        3. **:func:`window_refusal`** —— 写事务**之内**、重放检查**之后**。它读
           :meth:`chain_progress`，而那个读数只有在写事务里才**挡得住并发**：两个同时
           提交的自动受理里，后一个会看见前一个刚插进去的那一行（``open_runs=1``），
           于是它被 :func:`window_refusal` 的第二条拒掉。放在事务外读，两个都会看到
           ``open_runs=0``，于是**两个都过**，而这条链关于「对象数/累计预算」的累计
           在两次受理里各读到一个还没算上对方的数 —— 合起来超。与
           ``adapters/sqlite/runs.py`` 模块 docstring 那条「受理是一次读-判-写」是
           同一处教训，只是这次要读的不止一行。

        ``spent`` 是**这条链**的累计花费（逐科目），由调用方拿着
        :attr:`ChainProgress.reservations` 去账本读回来（``ports/budget.py`` 是金额的
        唯一权威，Run 记录读不到它）。缺省 ``None`` 的意思是「没读到账本读数」，而
        窗口在场时那是**一条拒绝**，不是一次跳过 —— 见 :func:`window_refusal` 第四条。
        没有窗口的规格（``manual``）用不到它，所以缺省值不会让任何既有调用点变红。

        ## 受理顺手做掉的第四件事：**把这一轮的折入账开成空的**

        受理写下的不止 ``research_run`` 那一行 —— 它**在同一个写事务里**给这一轮开一份
        空的折入账（§B17 条件 2）。这不是附带的好习惯，它是 :meth:`folds_of` 那一边
        能成立的前提：**「这一轮一行都没折」与「没有人记过这一轮折了什么」必须是两个
        可分辨的状态**。只留前一个（没有账 = 零折入）会让漏记读成零，而这两件事的处置
        相反 —— 一个该照常停表，一个该停下来查。见 :meth:`folds_of`。

        重放那条路径**不重开账**（它连写都不写，见上面的次序第 2 条）：一份账被重开
        会把已经记下的折入擦掉，而这一次调用的承诺恰恰是「一个字节都不改」。

        Raises:
            RunSpecError: :func:`admission_refusal` 或 :func:`window_refusal` 给出了理由。
            IdempotencyConflictError: 同一个键配了不同的 ``spec_sha256``。
            ValueError: ``spec_sha256`` 不是 64 位小写十六进制。它唯一的用途是判断
                「同一个键是不是同一个请求」，所以一个形状不对的值不会报错 —— 它只会让
                **每一次**提交都与别的不同，于是重发被读成新的。
        """

    @abstractmethod
    def get(self, run_id: str) -> Run | None:
        """按 id 取一轮；不存在时返回 ``None``（不抛）。

        不抛的理由与 ``JobStore.get`` 相同：调用方拿着一个 id 来问，而「没有这一轮」
        是它要的答案之一，不是一次异常。
        """

    # ------------------------------------------------------------------
    # 一条授权链走到哪了（§B17 条件 4）
    # ------------------------------------------------------------------
    @abstractmethod
    def chain_progress(self, *, workspace: str, window_digest: str) -> ChainProgress:
        """这条授权链**已经走了多远**。见 :class:`ChainProgress`。

        实现**只做一件事**：把这个工作区的行取出来，交给
        :func:`progress_of`。筛选（工作区、窗口摘要、结束没结束）与折叠（去重、
        计数）都在那一个函数里 —— 理由与 :func:`admission_refusal` 同一处：跨实现
        不能漂移的裁定写在模块里。

        **没有这一条链时返回零值**（``runs=0`` / ``objects=0`` / ``open_runs=0``），
        不抛也不返回 ``None``：「这条链一轮都还没开」是一个答案，而且正是第一次受理
        时会拿到的那个答案。一个 ``None`` 会让每个调用点各判一次「有没有」，而那些
        判断里漏掉的那一处会把「第一次」读成「读不到」。

        参数关键字化：两个都是字符串，位置传参时 ``workspace`` 与 ``window_digest``
        在调用点上长得一样，而它们搞反了不会报错 —— 只会恒返回零值，于是**每一次**
        自动受理都看起来像「这条链第一轮」。
        """

    # ------------------------------------------------------------------
    # 一次结束（§B17 条件 2）
    # ------------------------------------------------------------------
    @abstractmethod
    def stop(
        self,
        run_id: str,
        *,
        delta: RunDelta,
        status: RunStatus,
        at: datetime,
    ) -> Run:
        """结束这一轮：结局、产出与停表**在同一个写事务里**落下，返回结束后的那一行。

        ## 为什么是一个方法而不是三个

        结局（``stop_reason``）、产出（``delta``）、停表（``stopped_at``）三者
        同时有或同时无（``domain/run.py::Run.__post_init__`` 与本层同一条不变量，
        存储层另有等价的 ``CHECK`` 管住别的进程）。分成「先写结局、再补产出」会造出
        一个已结束而产出未写的窗口 —— 那个窗口里「它什么都没产出」与「产出丢了」
        长得一样，而这两件事的处置相反。

        ## 幂等：重放拿回同一行

        同一个 ``(status, delta)`` 再来一次**不是**第二次结束：它返回已经结束的那
        一行，一个字节都不改。判重放的依据是**这一套结局与产出**，不是这个方法被调
        过几次；``at`` 不比 —— 重放记的是第一次停表的那个时刻。

        Raises:
            RunStateError: 两种之一，消息里点名是哪一种 —— ``run_id`` 不存在；
                这一轮已经结束了，而这次带上来的结局与产出**不是**先前那一套。
            RunSpecError: :func:`ending_refusal` 给出了理由。
        """

    # ------------------------------------------------------------------
    # 这一轮折过哪几行（§B17 条件 2 的权威那一侧）
    # ------------------------------------------------------------------
    @abstractmethod
    def folds_of(self, run_id: str) -> tuple[FoldReceipt, ...]:
        """这一轮 Run **真的折进池子**的那几行，按折入次序。

        它是 ``close_run`` 那一侧唯一的权威，因为它是**唯一一处不看调用方说法**的读数：
        每一笔都由写池子的那个事务记下（``ports/pool.py::upsert_asset`` 的 ``fold=``），
        与那一行场地同生共死。调用方递上来的 ``folded`` 从「真源」降级成「一份要被核对
        的主张」时说穿了就是这一条。

        ## 三种状态，**不许塌成两种**

        1. **有两行或更多行** —— 这一轮折了几行，逐行在此。
        2. **有账、是空的**（``()``）—— 这一轮**真的**一行都没折。这是受理开账给出的
           读数（:meth:`admit`），也是一个正常结局：一轮跑完什么都没折进池子。
        3. **账本不在** —— 抛 :class:`~marketops.domain.errors.RunFoldLedgerError`，
           报文取自 :func:`fold_ledger_refusal`。**绝不返回 ``()``。**

        第 3 条是这一层存在的理由，不能让步。把「读不出来」读成「零折入」，恰好就是
        §B17 条件 2 要关掉的那条假账：折了却没记，然后结束时报一份空主张 —— 账照旧平，
        池子却变大了。**今天**盘上还有一条造出第 3 种状态的路径：一个来自还没有账本的
        版本的库。那条路同样必须停下来，而不是静默降级。

        ``run_id`` **不存在**时也抛同一个异常，只是报文说清了是哪一种（``run_exists``
        那一格），不返回 ``()``、不返回 ``None``：本层没有两种沉默 —— 与
        :func:`unknown_run_refusal` 那一处「不该被当成已经结束了」同一条纪律。

        Raises:
            RunFoldLedgerError: 账本不在（含 ``run_id`` 不在册）。
        """


