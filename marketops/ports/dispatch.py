"""``Dispatcher`` 抽象：把一件已编译的工作交给**外部执行器**，并读回它的状态。

## 它守的是哪一条

§6 逐字：**「Store admission and dispatch intent transactionally, reconcile Quay
task mapping …」**。前半句由 ``JobStore`` 守（``admit`` / ``compile_work_items``
在一个写事务里），后半句「reconcile … task mapping」是一个**跨系统**的动作，
所以它需要一份自己的契约：本地有一个 work item，外部有一个任务，两者之间那条
线是我们要维持的东西。

这条线会断，而断法只有两种，**两种都不报错**：

1. **同一件事被交出去两次** —— §8B 逐字禁止的 duplicate expensive work。两边
   都会正常跑完，账单付两遍，而报告上只会显示「工作多了一倍」。
2. **一件事被交出去零次** —— 本地记着「已派发」，外部什么都没有。它看起来与
   「派发了、还没跑完」一模一样，直到有人去等一个永远不会来的结果。

## 三个动词，以及它们各自唯一挡得住的那一种失败

* ``find(labels)`` —— 问「这件事在外部**已经有了吗**」。它是防第 1 条的**读**那
  一半，所以它有一个不能让步的要求：**「查到了零条」与「这次查询没跑成」必须是
  两种可区分的结果。** 一个把两者都报成 ``()`` 的实现会让「已经有了吗」这个
  问题的答案恒为「没有」，于是每一次重试都新建一个任务 —— 第 1 条失败。
  所以：查到了零条返回 ``()``，查询本身失败**抛** ``DispatchError``。
* ``create(unit, labels=...)`` —— 唯一的外部写入口。**它不得被用来判断存在性。**
  见 ``ExternalTask`` 与实现侧的 ``create`` 说明：外部的建任务面普遍是
  upsert，对一个已存在的 id 建一次会**静默成功**（退 0），于是「用 create 去试，
  成功了就当是新建的」会让两个并发的派发者都以为自己建了它。
* ``transition(...)`` —— 带 ``expected`` 的状态迁移，是防第 1 条的**写**那一半：
  读到的状态与据此写下的状态必须是同一个。这与 ``JobStore.set_state`` 是同一条
  纪律，两个系统的 CAS 在这里对齐。

## 为什么 ``find`` 收的是一**组** label 而不是一个

因为唯一能把「这件事的这次派发」认出来的东西是一个**合取**，不是一个字符串：
作业 id 与工作单元 id 各自都太粗（一个作业下有许多单元，一个单元可能在多个作业里
出现过同样的名字）。实现侧因此按 AND 语义过滤。收一组而不是「一个主 label」，
是为了让这个契约不必知道调用方用了哪几个 label —— 关联约定是**调用方**发明的，
见 ``application/dispatch.py``。

## 刻意**没有**的东西

* **没有 ``delete`` / ``cancel``。** 外部任务的收回不是这条路径的事。观测到的
  取消是**本地**作业的状态（``JobState.CANCELLED``），它管的是「不再派发新的」；
  已经交出去的那一个怎么处置需要一个写明理由的显式动词，而那件事今天在
  ``JobStore`` 那一侧（``release(reason=...)``），不在这里。
  一个 ``cancel(external_id)`` 会让人以为取消委托出去的活是免费的 —— 它不是。
* **没有 ``list_all`` / ``scan``。** 无过滤的列举在跨系统这条边界上是一句
  「把外面的东西全读进来」，而外部那张表里混着别人的工作。每次读都必须由一组
  label 收窄到我们自己的那些行。
* **没有超时参数、没有 retry 策略。** 那些是实现的事：一个把它写进契约的端口
  会把某一个实现的超时语义变成所有实现的前提。
* **没有 ``extra`` / 自由 JSON 的入口。** 只给 label，因为只有 label 是**可查的**
  —— 写进一个查不回来的字段等于把关联记在一个读不到的地方。
  上一条的 ``body`` **不是**这条禁止的那个 ``extra``，两者的区别值得写下来：被禁的
  是**关联**记在私有通道里（那会让「外面那个任务是我的哪一件」有两个来源，而其中
  一个查不回来）；``body`` 不是关联 —— 它是那件事**对外说的内容**，而且它是外部自己
  的一等字段（它自己会显示、自己可以编辑），不是我们塞进去的一段私有 JSON。同一个
  理由也解释了为什么它挂在 ``ExecutionUnit`` 上而不是 ``create`` 的一个参数上：
  ``create`` 是**唯一**的写入口，所以任何要写下去的东西都必须随那件事一起走过来。

本模块**不得**出现任何厂商名，由 ``tests/test_ports_are_contracts_only.py`` 执行。
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass


@dataclass(frozen=True)
class ExecutionUnit:
    """要交给外部执行器的一件事。

    ``unit_id`` 是**本地** id（``WorkItem.work_item_id``）。外部系统不认识它，
    外部认识的那个 id 由 **应用层**从 ``(job_id, unit_id)`` 确定性派生、再由
    ``create`` 回读确认 —— 两者之间的线就是这条边界要维持的东西，所以它们
    **不能是同一个字段**：一个「本地 id 就是外部 id」的设计会让「外部那个任务
    被删了」与「它从来就没建过」不可区分。

    这条边界上**没有**第三个 id 字段，是刻意的：外部 id 是那对本地 id 的函数，
    再立一个字段就等于给同一个事实起两个名字，而两个名字迟早会有一个开始说谎。
    那条命名规则住在 ``marketops.application.dispatch``（不是适配器里），理由
    在那个函数的 docstring 里 —— 一句话：正文必须写出那个名字。

    ``title`` 与 ``body`` 是这件事**对外说的那一面**：一行谁都能读的标题，加一段
    谁都能读的正文。两个都**必填、都没有缺省值** —— 缺省会让「调用方没想好怎么说
    清这件事」表现成一次成功的派发加上外部一行读不懂的条目，而那时已经付出了一次
    派发。为什么正文也在这一层：``create`` 是唯一的写入口，所以它只能从这里走
    （见模块 docstring 里 ``extra`` 那条）。

    正文里**不该**有指引：外部那张表是**外部**的看板，指引走市场侧的
    ``get_assignment``（§2.14 H3a）。这条边界的判据不在本层 —— 端口不知道谁提供
    指引、也不知道指引长什么样，它只知道这一段会被原样写下去。
    """

    unit_id: str
    job_id: str
    title: str
    body: str


@dataclass(frozen=True)
class ExternalTask:
    """外部系统里一个任务，按它自己报回来的样子。

    ``status`` 是**外部闭集里的字符串**，不是本地 ``JobState``：两套状态机不是
    同一个（本地的没有 done，外部的有），把它们折成一个的共同域只会让两边的
    取值都变得不可信。翻译发生在需要它的那一层，且是显式的。

    ``labels`` 逐字保留。它是**唯一**能让一次查询找回这个任务的东西，所以回执里
    必须带着它 —— 一个只回 id 的 ``create`` 让调用方无法验证「刚才那组 label
    真的写上去了」，而写不上去的 label 是一个查不回来的任务。
    """

    external_id: str
    status: str
    labels: tuple[str, ...]


@dataclass(frozen=True)
class WorkerExitRecord:
    """外部执行器对**一次 worker 退出**的自述 —— 它自己那本账里的一行。

    ## 为什么它是一个契约类型，而不是某个实现内部的东西

    因为「外面怎么判这一次退出」是**报告的一等事实**。本仓的完成判据与它的判据
    不是同一个（研究件不产出提交、没有 worktree），两者不一致时报告必须把两边都
    印出来。丢掉外面那一句，「为什么看板说 ``done`` 而外部那本账说没落地」在报告
    里就没有任何痕迹 —— 而那正是 2026-09-23 那次运行留下的形状。

    ## 字段名逐字取自外部那本账

    它是一份**读回来的原文**，而改一个名字就多一次翻译；翻译会漂移，漂移的那天
    回执里那一格读起来仍然正常。唯一的例外是 ``task_id``（外部那一格叫 ``task``，
    而那个词是动词还是名词读不出来），改名写在字段的注释里。

    ## 缺值 ≠ 某个取值

    ``state`` 之外的四格都是 ``| None``：外部**没写**那一格，与「它写了某个值」
    是两件事。参考实现对任何非正常结局都把 ``exit_code`` 写成 ``null`` ——
    那是「这一格不适用」，不是 0。

    ## 它**不是**判决

    本类型只回答「外面说发生了什么」。它与本仓的完成语义谁说话算数，是
    ``application/research_terminal.py`` 的事：那里把这一份原文标成 **N/A**，
    而不是把它升格成一个失败。
    """

    #: 外部那个任务 id。**唯一一处改名**（外部那本账里这一格叫 ``task``）。
    task_id: str
    #: 这一行是什么时候写下的（外部那本账的 ``ts``）。
    recorded_at: str
    #: 外部自己的结局词（那一格叫 ``final_state``）。**本仓不翻译它** —— 两套语义
    #: 不是同一个，折成一个共同域只会让两边的取值都变得不可信。
    final_state: str
    #: 外部给的那个理由。非正常结局才有；正常结局是 ``None``（不是空串）。
    reason: str | None
    #: 进程退出码。非正常结局外部一律不填。
    exit_code: int | None
    #: 这次 worker 活了多久。外部没写这一格时是 ``None``。
    wall_clock_ms: int | None


class Dispatcher(ABC):
    """外部执行器的契约。三个动词，全部关键字化。"""

    @abstractmethod
    def find(self, *, labels: Sequence[str]) -> tuple[ExternalTask, ...]:
        """按一组 label（**AND 语义**）找回我们自己的那些任务。

        返回空元组表示「**查到了零条**」——这是一个**答案**。查询本身没能跑成
        （执行器起不来、输出读不懂、权限不对）必须抛 ``DispatchError``。

        这两者混起来是本接口最贵的一种错：调用方用 ``find`` 的结果决定要不要
        ``create``，于是「查询失败被读成零条」会稳定地生产重复派发，而且每一次
        都伴随着一次成功的 ``create`` —— 报告上全是成功。

        返回的条数**不做归一**。查到两条就是两条，由调用方决定那是不是一个要
        停下来报告的事实；在这里挑一条返回等于把一个「同一个单元被派发了两遍」
        的证据扔掉。

        Raises:
            DispatchError: 执行器没能给出一份可读的答案。
            ValueError: ``labels`` 为空。一次不按 label 收窄的查询在外部那张表上
                是「把别人的工作也读进来」。
        """

    @abstractmethod
    def create(
        self, unit: ExecutionUnit, *, labels: Sequence[str], status: str
    ) -> ExternalTask:
        """在外部建（或对齐）一个任务，把 ``labels`` 与 ``status`` 写上，**读回来**。

        ``status`` 是**调用方**选的初始外部状态，本契约不替它选、也不校验它的
        取值：外部那套状态机是外部的，把它的成员抄成这里的一份闭集，就是把这个
        仓库里的一条声明放到一个外部的实现前面（§2.9 记过一次：外部的**声明
        文件**与它的实现不一致，而闭集要从实现那侧读）。不合法的取值由对面拒绝，
        拒绝的报文原样上抛。

        ## 它不是存在性判据

        外部的建任务面普遍是 **upsert**：对一个已经存在的 id 再建一次会静默
        成功。所以本方法的返回值是**外部实际报回来的样子**（含它自己那份
        ``labels``），而不是一次「我建成功了」的宣称。调用方要先 ``find``、
        再 ``create``，并且**必须**核对回读的 ``labels`` —— 一个 label 没写上去
        的任务从 ``find`` 那边看等于不存在。

        ## 幂等

        同一件事重复调用本方法**不得**在外部留下两个任务。实现靠一个由
        ``unit`` 派生的**确定性**外部 id 做到这一点：并发的两个派发者算出同一个
        id，第二个的 create 是原地对齐而不是新建。用随机 id 的实现会违反这一条，
        而违反它的后果正是第 1 条失败。

        Raises:
            DispatchError: 执行器没能给出一份可读的答案，或**回读不回来** ——
                写下去了却按同一组 label 查不到恰好那一个（label 没落盘、或这组
                label 下的任务不止一个）。两种都必须抛，因为一个查不回来的任务
                与一个不存在的任务从 ``find`` 那边看是同一件事。
            ValueError: ``labels`` 为空，或 ``status`` / ``unit.title`` 为空。
        """

    @abstractmethod
    def transition(
        self, external_id: str, *, expected: str, status: str
    ) -> ExternalTask:
        """把外部任务从 ``expected`` 迁到 ``status``，**一次 CAS**。

        ``expected`` 必填。外部那个状态不是我们独占的（人在 UI 里也能改），所以
        「读到什么、据此写什么」必须是同一次操作 —— 这是能跨机防重复写的唯一
        原语，也是它与 ``JobStore.set_state`` 对齐的地方。

        Raises:
            ExternalStateError: 外部当前状态不是 ``expected``（有别人先写了），
                或者 ``external_id`` 在外部不存在。**两种都表示「本地那张映射与
                外面对不上了」**，处置是停下重读，不是重试这次写。
            DispatchError: 执行器没能给出一份可读的答案。
        """
