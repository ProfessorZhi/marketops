#!/usr/bin/env python3
"""Offline installer smoke probe for the MarketOps Research plugin.

Answers one question per supported host, without network, credentials or spend:
*does this build expose exactly one managed MarketOps MCP, with no enabled
direct-vendor bypass, and does that MCP answer `tools/list` with host-compatible
schemas?*

Two layers, deliberately separable:

* **Static audits** (manifests, configs, Skills, packaged tree) need nothing but
  the files, so they run on a machine with no `mcp` package installed.
* **Wire probe** launches the bundled entry script over stdio, calls
  `initialize` + `tools/list` and audits what the host would actually receive.
  It is the only check that catches "the Skill is present but the MCP silently
  failed to start", which has been observed on a real host.

This probe never authenticates, never calls a provider and never writes into the
plugin tree. Everything it reports is measured, not assumed.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from research_mcp_facade import audit_schema  # noqa: E402  (sibling module)

#: Host manifests that must exist for the one plugin to load on each host.
HOST_MANIFESTS = {
    "claude-code": ".claude-plugin/plugin.json",
    "codex": ".codex-plugin/plugin.json",
    "workbuddy": "plugin.json",
}

#: Every MCP config shipped in the plugin. Both are generated by the installer;
#: a host may read either, so both must satisfy the same contract.
MCP_CONFIGS = (".mcp.json", "mcp.json")

#: The only server name a shipped config may declare.
MANAGED_SERVER_NAME = "marketops-research"

#: Environment variable names the plugin is allowed to ask a host to pass
#: through. A name outside this set (or any wildcard) is a defect: it would let a
#: host hand the process variables nobody reviewed.
SAFE_ENV_PASSTHROUGH = frozenset({
    "MARKETOPS_RESEARCH_DATA_ROOT", "MARKETOPS_RESEARCH_CONFIG",
    "MARKETOPS_RESEARCH_PYTHON", "MARKETOPS_RESEARCH_ALLOW_NETWORK",
    "MARKETOPS_RESEARCH_MAX_EXTERNAL_CALLS", "MARKETOPS_FETCH_ALLOWED_DOMAINS",
    "MARKETOPS_SEARCH_ALLOW_NETWORK", "MARKETOPS_SEARCH_MAX_CALLS",
    "MARKETOPS_TINYFISH_AGENT_ALLOW_PAID", "MARKETOPS_TINYFISH_ACCOUNT_ALIAS",
    "SERPAPI_API_KEY", "SERPER_API_KEY", "CRAWL4AI_API_KEY",
    "TINYFISH_API_KEY", "TINYFISH_MCP_ACCESS_TOKEN", "TYPESAFE_API_KEY", "DEEPSEEK_API_KEY",
})

#: A vendor MCP endpoint. A shipped config that declares one of these as an
#: enabled server is a direct paid bypass, whatever it is named.
VENDOR_ENDPOINTS = (
    "mcp.tinyfish.ai", "agent.tinyfish.ai", "api.crawl4ai.com",
    "google.serper.dev", "serpapi.com", "mcp.serpapi.com",
    "typesafe.ai", "api.typesafe.ai",
)

#: Credential-shaped literals. A manifest is a public artifact; a value here is
#: a leaked secret, not a template.
SECRET_PATTERNS = (
    re.compile(r"\b(sk|pk|rk)-[A-Za-z0-9]{16,}"),
    re.compile(r"\bBearer\s+[A-Za-z0-9._~+/-]{20,}"),
    re.compile(r"\bey[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\."),
)

#: Skills whose whole subject is one vendor. Their descriptions must not instruct
#: a host to prefer that vendor globally.
VENDOR_SKILL_PREFIX = "marketops-"

#: Server fields Claude Code actually honours in a *plugin* `.mcp.json`.
#:
#: Measured on Claude Code 2.1.272: a field outside this set does not degrade
#: gracefully — the server is reported `failed` in the session's init event and
#: is never launched, while `claude mcp list` still health-checks the same
#: config green. `default_tools_approval_mode` cost exactly that until it was
#: removed here, which is why the rule is an allowlist and not "looks harmless".
CLAUDE_PLUGIN_SERVER_FIELDS = frozenset({
    "type", "command", "args", "env", "env_vars", "cwd",
})

#: Fields the generator deliberately writes for the non-Claude configs
#: (`build_client_bundles.py` emits `timeout`; the installer rewrites paths).
#: These are ours, so a field outside this set means the generator changed
#: without this list changing with it — a real finding, not a host question.
GENERATOR_WRITTEN_SERVER_FIELDS = CLAUDE_PLUGIN_SERVER_FIELDS | frozenset({"timeout"})

#: Fields carried by the generic (non-Claude) config for hosts there is no
#: device to test against. Reported as a note, never silently accepted: an
#: unverified field on an untested host is a fact about this machine's evidence,
#: not a statement that the field is fine there.
UNTESTED_HOST_SERVER_FIELDS = frozenset({
    "default_tools_approval_mode",
})


def _finding(kind: str, detail: str, path: str = "") -> dict:
    return {"kind": kind, "detail": detail, "path": path}


def _iter_files(root: Path, suffixes: tuple[str, ...]):
    for path in sorted(root.rglob("*")):
        if path.is_file() and path.suffix in suffixes:
            yield path


def audit_mcp_config(config_path: Path) -> dict:
    """One config: exactly one server, the managed name, no vendor endpoint, no secret.

    `.mcp.json` is the Claude Code plugin config, so its server fields are held to
    the set that host honours. The other config names no host in particular; a
    field there that no device here can exercise is reported as a note rather
    than passed as verified.
    """
    claude_config = config_path.name == ".mcp.json"
    findings: list[dict] = []
    notes: list[dict] = []
    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {"ok": False, "servers": [], "notes": [],
                "findings": [_finding("CONFIG_UNREADABLE", type(exc).__name__, str(config_path))]}
    servers = data.get("mcpServers") or data.get("mcp_servers") or {}
    names = sorted(servers)
    if len(names) != 1:
        findings.append(_finding("NOT_EXACTLY_ONE_MCP", f"declares {len(names)}: {names}",
                                 str(config_path)))
    for name, server in servers.items():
        if name != MANAGED_SERVER_NAME:
            findings.append(_finding("UNMANAGED_SERVER_NAME", name, str(config_path)))
        blob = json.dumps(server, ensure_ascii=False)
        for endpoint in VENDOR_ENDPOINTS:
            if endpoint in blob:
                findings.append(_finding("DIRECT_VENDOR_ENDPOINT", endpoint, str(config_path)))
        for pattern in SECRET_PATTERNS:
            if pattern.search(blob):
                findings.append(_finding("SECRET_LITERAL", pattern.pattern, str(config_path)))
        for var in (server.get("env_vars") or []):
            if var not in SAFE_ENV_PASSTHROUGH:
                findings.append(_finding("UNAPPROVED_ENV_NAME", var, str(config_path)))
        for var in (server.get("env") or {}):
            if var not in SAFE_ENV_PASSTHROUGH and var != "PLAYWRIGHT_BROWSERS_PATH":
                findings.append(_finding("UNAPPROVED_ENV_NAME", var, str(config_path)))
        unknown = sorted(set(server) - CLAUDE_PLUGIN_SERVER_FIELDS)
        for field in unknown:
            if claude_config:
                findings.append(_finding("HOST_FOREIGN_FIELD", field, str(config_path)))
            elif field in UNTESTED_HOST_SERVER_FIELDS:
                notes.append(_finding("FIELD_ON_UNTESTED_HOST", field, str(config_path)))
            elif field not in GENERATOR_WRITTEN_SERVER_FIELDS:
                findings.append(_finding("UNEXPECTED_SERVER_FIELD", field, str(config_path)))
    return {"ok": not findings, "servers": names, "findings": findings, "notes": notes}


def audit_plugin_tree(root: Path) -> dict:
    """Manifests, MCP configs, entry-point reachability and packaged-vendor scan."""
    findings: list[dict] = []
    notes: list[dict] = []
    manifests: dict[str, bool] = {}
    for host, relative in HOST_MANIFESTS.items():
        present = (root / relative).is_file()
        manifests[host] = present
        if not present:
            findings.append(_finding("HOST_MANIFEST_MISSING", host, relative))
    configs: dict[str, dict] = {}
    for relative in MCP_CONFIGS:
        path = root / relative
        if not path.is_file():
            findings.append(_finding("MCP_CONFIG_MISSING", relative, relative))
            continue
        result = audit_mcp_config(path)
        configs[relative] = result
        findings.extend(result["findings"])
        notes.extend(result.get("notes") or [])
        entry = ""
        try:
            server = next(iter((json.loads(path.read_text(encoding="utf-8"))
                                .get("mcpServers") or {}).values()))
            args = server.get("args") or []
            entry = args[-1] if args else ""
        except (OSError, ValueError, StopIteration):
            entry = ""
        if entry and not entry.endswith("research_mcp.py"):
            findings.append(_finding("ENTRY_IS_NOT_MANAGED_MCP", entry, relative))
    # Every declared entry must exist in this tree, or the host gets a server that
    # silently never starts.
    for script in ("research_mcp.py", "research_mcp_facade.py", "launch_research_mcp.sh"):
        if not (root / "scripts" / script).is_file():
            findings.append(_finding("ENTRY_SCRIPT_MISSING", script, "scripts/"))
    # Vendor configs may exist for developers but must not be an enabled server
    # inside the distributable tree.
    for path in _iter_files(root, (".json",)):
        try:
            blob = path.read_text(encoding="utf-8")
        except OSError:
            continue
        if not any(endpoint in blob for endpoint in VENDOR_ENDPOINTS):
            continue
        try:
            data = json.loads(blob)
        except ValueError:
            continue
        if isinstance(data, dict) and (data.get("mcpServers") or data.get("mcp_servers")):
            findings.append(_finding("PACKAGED_VENDOR_MCP", "enabled vendor server",
                                     str(path.relative_to(root))))
    return {"ok": not findings, "manifests": manifests, "configs": configs,
            "findings": findings, "notes": notes}


def audit_skills(root: Path) -> dict:
    """Every Skill loads and none names a credential or a raw vendor endpoint."""
    findings: list[dict] = []
    skills = sorted((root / "skills").glob("*/SKILL.md"))
    for skill in skills:
        text = skill.read_text(encoding="utf-8")
        relative = str(skill.relative_to(root))
        head = text.split("---", 2)
        if len(head) < 3 or "name:" not in head[1] or "description:" not in head[1]:
            findings.append(_finding("SKILL_FRONTMATTER_INCOMPLETE", "", relative))
        for pattern in SECRET_PATTERNS:
            if pattern.search(text):
                findings.append(_finding("SECRET_LITERAL", pattern.pattern, relative))
    return {"ok": not findings, "skill_count": len(skills), "findings": findings}


def audit_windows_config(config_path: Path) -> dict:
    """A Windows host has no `sh`; the config must not depend on one.

    This is a *shape* check only. No Windows device is authorized for this wave,
    so the result is a compatibility statement, never a Windows test result.
    """
    findings: list[dict] = []
    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {"ok": False, "findings": [_finding("CONFIG_UNREADABLE", type(exc).__name__,
                                                   str(config_path))]}
    for name, server in (data.get("mcpServers") or {}).items():
        command = server.get("command", "")
        if command in ("sh", "bash", "/bin/sh", "/bin/bash"):
            findings.append(_finding("POSIX_SHELL_ON_WINDOWS", f"{name}:{command}",
                                     str(config_path)))
        if command.endswith(".sh") or any(str(a).endswith(".sh") for a in server.get("args") or []):
            findings.append(_finding("SHELL_SCRIPT_ENTRY", name, str(config_path)))
        if server.get("type") not in (None, "stdio"):
            findings.append(_finding("NON_STDIO_TRANSPORT", str(server.get("type")),
                                     str(config_path)))
        if server.get("cwd"):
            findings.append(_finding("ABSOLUTE_CWD_PINNED", str(server["cwd"]), str(config_path)))
    return {"ok": not findings, "findings": findings}


def probe_stdio_tools(python: str, entry: Path, *, data_root: Path,
                      timeout_s: float = 120.0) -> dict:
    """Launch `entry` over stdio and report what the host would receive.

    The environment is pinned to a throwaway data root with every network switch
    off, so a successful probe cannot have spent money or reached a vendor.
    """
    import asyncio

    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client

    env = dict(os.environ)
    env.update({
        "MARKETOPS_RESEARCH_DATA_ROOT": str(data_root),
        "MARKETOPS_SEARCH_ALLOW_NETWORK": "0",
        "MARKETOPS_SEARCH_MAX_CALLS": "0",
        "MARKETOPS_RESEARCH_ALLOW_NETWORK": "0",
        "MARKETOPS_RESEARCH_MAX_EXTERNAL_CALLS": "0",
        "MARKETOPS_TINYFISH_AGENT_ALLOW_PAID": "0",
    })
    for name in ("SERPAPI_API_KEY", "SERPER_API_KEY", "CRAWL4AI_API_KEY",
                 "TINYFISH_API_KEY", "TYPESAFE_API_KEY", "TINYFISH_MCP_ACCESS_TOKEN",
                 "DEEPSEEK_API_KEY"):
        env.pop(name, None)

    async def run() -> dict:
        params = StdioServerParameters(command=python, args=[str(entry)], env=env)
        async with stdio_client(params) as (read, write):
            async with ClientSession(read, write) as session:
                init = await session.initialize()
                listed = await session.list_tools()
                tools = listed.tools
                schemas = [{"name": t.name, "schema": t.input_schema} for t in tools]
                findings: list[dict] = []
                for item in schemas:
                    for hit in audit_schema(item["schema"]):
                        findings.append(_finding("HOST_UNSUPPORTED_SCHEMA",
                                                 hit["keyword"], f'{item["name"]}{hit["path"]}'))
                vendor = [item["name"] for item in schemas
                          if not item["name"].startswith("marketops_")]
                for name in vendor:
                    findings.append(_finding("VENDOR_NAMED_TOOL", name, str(entry)))
                surface = audit_tool_surface(item["name"] for item in schemas)
                return {
                    "ok": not findings,
                    "server": {"name": init.server_info.name, "version": init.server_info.version},
                    "tool_count": len(schemas),
                    "tools": [item["name"] for item in schemas],
                    "surface": surface,
                    "findings": findings,
                }

    return asyncio.run(asyncio.wait_for(run(), timeout=timeout_s))


#: What `setup_clients.py` writes for each host, relative to the install destination.
CODEX_MARKETPLACE_PATH = Path(".agents") / "plugins" / "marketplace.json"
CLAUDE_PLUGIN_PATH = Path("plugins") / "marketops-research-assistant"
CONNECTOR_ROOT = Path("connectors") / "workbuddy"

#: Files a WorkBuddy connector is useless without. The token form is how that host
#: collects credentials, so a connector without it installs and then cannot run.
CONNECTOR_REQUIRED_FILES = ("connector-meta.json", "icon.svg", "mcp.json")


def audit_codex_package(dest: Path) -> dict:
    """The Codex marketplace the installer generates, judged as Codex would read it.

    Nothing here claims Codex *behaves* correctly: no Codex device is authorized.
    It claims the generated artifact is internally consistent — every path it
    names resolves inside the install, and the plugin it points at carries one
    managed MCP whose entry exists.
    """
    findings: list[dict] = []
    marketplace_path = dest / CODEX_MARKETPLACE_PATH
    if not marketplace_path.is_file():
        return {"ok": False, "findings": [_finding("CODEX_MARKETPLACE_MISSING", "",
                                                   str(CODEX_MARKETPLACE_PATH))]}
    try:
        data = json.loads(marketplace_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {"ok": False, "findings": [_finding("CODEX_MARKETPLACE_UNREADABLE",
                                                   type(exc).__name__,
                                                   str(CODEX_MARKETPLACE_PATH))]}
    entries = data.get("plugins")
    if not isinstance(entries, list) or len(entries) != 1:
        findings.append(_finding("CODEX_MARKETPLACE_NOT_ONE_PLUGIN",
                                 f"plugins={entries!r}"[:120], str(CODEX_MARKETPLACE_PATH)))
        return {"ok": False, "findings": findings}
    entry = entries[0]
    source = (entry.get("source") or {})
    declared = source.get("path", "")
    if source.get("source") != "local" or not isinstance(declared, str):
        findings.append(_finding("CODEX_SOURCE_NOT_LOCAL", str(source)[:120],
                                 str(CODEX_MARKETPLACE_PATH)))
        return {"ok": False, "findings": findings}
    # A relative path is resolved against the destination, exactly as the host
    # would; an escaping path would register something nobody packaged.
    #
    # Strip the leading "./" as a *prefix*: `lstrip("./")` is a character-set
    # strip, which quietly turns "../../elsewhere" into "elsewhere" and would
    # make this guard pass the very input it exists to reject.
    relative = declared[2:] if declared.startswith("./") else declared
    plugin_dir = (dest / relative).resolve()
    try:
        plugin_dir.relative_to(dest.resolve())
    except ValueError:
        findings.append(_finding("CODEX_SOURCE_ESCAPES_DEST", declared,
                                 str(CODEX_MARKETPLACE_PATH)))
        return {"ok": False, "findings": findings}
    manifest_path = plugin_dir / ".codex-plugin" / "plugin.json"
    if not manifest_path.is_file():
        findings.append(_finding("CODEX_PLUGIN_MANIFEST_MISSING", declared,
                                 str(manifest_path)))
        return {"ok": False, "findings": findings}
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        findings.append(_finding("CODEX_PLUGIN_MANIFEST_UNREADABLE", type(exc).__name__,
                                 str(manifest_path)))
        return {"ok": False, "findings": findings}
    config_name = (manifest.get("mcpServers") or "").lstrip("./")
    if not config_name:
        findings.append(_finding("CODEX_MANIFEST_NAMES_NO_MCP", "", str(manifest_path)))
    else:
        config_path = plugin_dir / config_name
        if not config_path.is_file():
            findings.append(_finding("CODEX_MCP_CONFIG_MISSING", config_name,
                                     str(manifest_path)))
        else:
            result = audit_mcp_config(config_path)
            findings.extend(result["findings"])
    for skill_dir in sorted((plugin_dir / "skills").glob("*/SKILL.md")):
        if not skill_dir.is_file():
            findings.append(_finding("CODEX_SKILL_MISSING", str(skill_dir), str(plugin_dir)))
    return {"ok": not findings, "plugin_dir": str(plugin_dir), "findings": findings}


def audit_workbuddy_package(dest: Path) -> dict:
    """The WorkBuddy connector the builder generates.

    Shape only, and stated as such: the connector's `enabledTools`/token
    behaviour has no device here to exercise it.
    """
    findings: list[dict] = []
    dest = dest.resolve()
    receipt_path = dest / "WORKBUDDY_BUNDLE.json"
    if receipt_path.exists():
        try:
            if receipt_path.is_symlink():
                raise ValueError("SYMLINK")
            receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
            selected = Path(receipt["directory"])
            connector = selected.resolve()
            contained = dest / "connectors"
            if (not selected.is_absolute() or not connector.is_relative_to(contained)
                    or not connector.is_dir() or selected.is_symlink()):
                raise ValueError("OUTSIDE_INSTALL")
        except (OSError, ValueError, TypeError, KeyError):
            return {"ok": False, "findings": [_finding("CONNECTOR_RECEIPT_INVALID", "",
                                                       receipt_path.name)]}
    else:
        # Compatibility for earlier installers and stand-alone test fixtures.
        root = dest / CONNECTOR_ROOT
        if not root.is_dir():
            return {"ok": False, "findings": [_finding("CONNECTOR_ROOT_MISSING", "",
                                                       str(CONNECTOR_ROOT))]}
        connectors = [p for p in sorted(root.iterdir()) if p.is_dir()]
        if len(connectors) != 1:
            findings.append(_finding("CONNECTOR_NOT_EXACTLY_ONE", f"{len(connectors)} dirs",
                                     str(CONNECTOR_ROOT)))
            return {"ok": False, "findings": findings}
        connector = connectors[0]
    for name in CONNECTOR_REQUIRED_FILES:
        if not (connector / name).is_file():
            findings.append(_finding("CONNECTOR_FILE_MISSING", name,
                                     str(connector.relative_to(dest))))
    meta_path = connector / "connector-meta.json"
    if meta_path.is_file():
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            meta = {}
            findings.append(_finding("CONNECTOR_META_UNREADABLE", type(exc).__name__,
                                     str(meta_path.relative_to(dest))))
        if meta:
            for field in ("name", "type", "version"):
                if not meta.get(field):
                    findings.append(_finding("CONNECTOR_META_FIELD_MISSING", field,
                                             str(meta_path.relative_to(dest))))
            if meta.get("type") != "mcp":
                findings.append(_finding("CONNECTOR_TYPE_NOT_MCP", str(meta.get("type")),
                                         str(meta_path.relative_to(dest))))
    config_path = connector / "mcp.json"
    if config_path.is_file():
        result = audit_mcp_config(config_path)
        findings.extend(result["findings"])
        try:
            server = next(iter(json.loads(config_path.read_text(encoding="utf-8"))
                               ["mcpServers"].values()))
            args = [a for a in (server.get("args") or []) if isinstance(a, str)]
            entry = args[-1] if args else ""
            if not entry or not (connector / Path(entry).name).is_file():
                # The generated config names an absolute path on the build
                # machine; the script must at least exist in the package that
                # travels with it.
                script = connector / "scripts" / Path(entry).name
                if not entry or not script.is_file():
                    findings.append(_finding("CONNECTOR_ENTRY_MISSING", entry or "(none)",
                                             str(config_path.relative_to(dest))))
        except (OSError, ValueError, KeyError, StopIteration):
            pass
    token_path = connector / "token-schema.json"
    if token_path.is_file():
        try:
            token = json.loads(token_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            token = {}
            findings.append(_finding("TOKEN_SCHEMA_UNREADABLE", type(exc).__name__,
                                     str(token_path.relative_to(dest))))
        blob = json.dumps(token, ensure_ascii=False)
        for pattern in SECRET_PATTERNS:
            if pattern.search(blob):
                findings.append(_finding("SECRET_LITERAL", pattern.pattern,
                                         str(token_path.relative_to(dest))))
        for field in token.get("fields") or []:
            key = field.get("key", "") if isinstance(field, dict) else ""
            if key and key not in SAFE_ENV_PASSTHROUGH:
                findings.append(_finding("UNAPPROVED_ENV_NAME", key,
                                         str(token_path.relative_to(dest))))
    return {"ok": not findings, "connector": str(connector.relative_to(dest)),
            "findings": findings}


def audit_installed_interpreter(dest: Path) -> dict:
    """Does the installed package's private interpreter exist and import MCP?

    Codex requires a bare host command, so its installed config uses a small
    stdlib launcher and records the private venv interpreter in ``env``. Other
    generated configs may continue to bind that interpreter directly.
    """
    findings: list[dict] = []
    notes: list[dict] = []
    config = dest / CLAUDE_PLUGIN_PATH / "mcp.json"
    if not config.is_file():
        return {"ok": False, "command": None, "can_import_mcp": None,
                "findings": [_finding("GENERATED_CONFIG_MISSING", "",
                                      str(CLAUDE_PLUGIN_PATH / "mcp.json"))],
                "notes": []}
    try:
        server = next(iter(json.loads(config.read_text(encoding="utf-8"))
                           ["mcpServers"].values()))
        command = str(server.get("command", ""))
        interpreter = str((server.get("env") or {}).get("MARKETOPS_RESEARCH_PYTHON")
                          or command)
    except (OSError, ValueError, KeyError, StopIteration):
        return {"ok": False, "command": None, "can_import_mcp": None,
                "findings": [_finding("GENERATED_CONFIG_UNREADABLE", "", str(config))],
                "notes": []}
    if not command:
        findings.append(_finding("GENERATED_CONFIG_HAS_NO_INTERPRETER", "", str(config)))
        return {"ok": False, "command": None, "can_import_mcp": None,
                "findings": findings, "notes": notes}
    if not Path(interpreter).is_file():
        findings.append(_finding("BOUND_INTERPRETER_MISSING", interpreter, str(config)))
        return {"ok": False, "command": command, "interpreter": interpreter,
                "can_import_mcp": None,
                "findings": findings, "notes": notes}
    try:
        can_import = subprocess.run([interpreter, "-c", "import mcp"],
                                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                    timeout=60).returncode == 0
    except (OSError, subprocess.SubprocessError):
        can_import = False
    if not can_import:
        notes.append(_finding(
            "INTERPRETER_LACKS_MCP",
            f"{interpreter} cannot import mcp; the MCP cannot start until "
            "`setup_clients.py --install-deps` (or a private venv) provides it",
            str(config)))
    return {"ok": not findings, "command": command, "interpreter": interpreter,
            "can_import_mcp": can_import,
            "findings": findings, "notes": notes}


def audit_client_packages(dest: Path) -> dict:
    """All three hosts' generated artifacts, from one install destination."""
    dest = dest.resolve()
    claude_root = dest / CLAUDE_PLUGIN_PATH
    claude = (audit_plugin_tree(claude_root) if claude_root.is_dir()
              else {"ok": False,
                    "findings": [_finding("CLAUDE_PLUGIN_PATH_MISSING", "",
                                          str(CLAUDE_PLUGIN_PATH))]})
    codex = audit_codex_package(dest)
    workbuddy = audit_workbuddy_package(dest)
    interpreter = audit_installed_interpreter(dest)
    findings = (claude.get("findings", []) + codex["findings"] + workbuddy["findings"]
                + interpreter["findings"])
    notes = (list(codex.get("notes") or []) + list(workbuddy.get("notes") or [])
             + list(interpreter.get("notes") or []))
    return {
        "destination": str(dest),
        "claude_code": claude,
        "codex": codex,
        "workbuddy": workbuddy,
        "installed_interpreter": interpreter,
        "notes": notes,
        "ok": bool(claude.get("ok") and codex["ok"] and workbuddy["ok"]
                   and interpreter["ok"]),
        "findings": findings,
    }


#: The launcher a host config can name on any OS family.
OS_NEUTRAL_LAUNCHER = "launch_research_mcp.py"

#: POSIX-only commands are invalid in the installed Windows artifact. Codex's
#: plugin parser also rejects absolute commands, so its installer output uses a
#: bare Python executable plus the OS-neutral launcher and a venv path in env.
POSIX_ONLY_COMMANDS = ("sh", "bash", "/bin/sh", "/bin/bash")


#: Tools that reach a provider without passing the managed gateway's S0 gate.
#:
#: This is the inventory as of the wave-6 candidate: `marketops_search` calls
#: `dual_search_mcp.search` directly, and the six others dispatch through
#: `research_provider_extensions.invoke`. They are *advertised to the host
#: alongside* `marketops_managed_call`, and nothing in the shipped configs
#: restricts the tool surface, so an Agent can pick the ungated path.
#:
#: The list is expected to shrink to empty when the provider lane retires them.
#: When that happens this constant is what must be updated — a stale entry here
#: would report a bypass that no longer exists, which is its own kind of lie.
COMPAT_PROVIDER_TOOLS = frozenset({
    "marketops_search", "marketops_crawl", "marketops_tinyfish",
    "marketops_serpapi_mcp_search", "marketops_tinyfish_agent",
    "marketops_tinyfish_agent_wait", "marketops_jev_choice",
})
# These names now translate arguments to research_mcp.managed_call. They are
# retained for customers, but there are no direct provider dispatchers among
# them. The runtime routing test checks that structural invariant.
LEGACY_VENDOR_TOOLS = frozenset()

#: The single tool that is allowed to reach a provider, and only through S0.
MANAGED_ENTRY_TOOL = "marketops_managed_call"


def audit_tool_surface(tool_names) -> dict:
    """Classify the host-visible tool surface: managed path vs ungated vendor path.

    A tool being vendor-capable is not itself a defect; being reachable *beside*
    the managed entry, with no S0 gate in front of it, is. Reported as RED rather
    than as a note because the difference is a policy bypass, not a preference.
    """
    names = list(tool_names)
    legacy = sorted(set(names) & LEGACY_VENDOR_TOOLS)
    findings = []
    if legacy:
        findings.append(_finding(
            "LEGACY_VENDOR_TOOL_EXPOSED",
            f"{len(legacy)} vendor-capable tool(s) reachable without the S0 gate: "
            + ", ".join(legacy),
            ""))
    if MANAGED_ENTRY_TOOL not in names and set(names) & COMPAT_PROVIDER_TOOLS:
        findings.append(_finding("NO_MANAGED_ENTRY_BESIDE_LEGACY", MANAGED_ENTRY_TOOL, ""))
    return {
        "severity": "RED" if findings else "OK",
        "tool_count": len(names),
        "managed_entry_present": MANAGED_ENTRY_TOOL in names,
        "legacy_vendor_tools": legacy,
        "findings": findings,
    }


def _looks_like_version_floor(key: str) -> bool:
    """True for keys that read like "this plugin needs host >= X".

    A rule, not a list: `minClaudeCodeVersion`, `minimumVersion`, `min_cli_version`
    and `engines` should all be found, while the plugin's own `version` must not
    be mistaken for a floor.
    """
    k = key.lower().replace("-", "_")
    if "engines" in k or "compatibility" in k:
        return True
    if "version" not in k:
        return False
    return k.startswith("min") or "minimum" in k or "requires" in k or "required" in k


def audit_host_version_floor(root: Path) -> dict:
    """Does any manifest declare which host versions this plugin supports?

    Nothing here invents a field. If no manifest declares a floor, the honest
    statement is that compatibility is *measured on the hosts someone ran*, not
    promised — and a reader who finds no note will assume the opposite.
    """
    declared: dict[str, str] = {}
    for host, relative in HOST_MANIFESTS.items():
        path = root / relative
        if not path.is_file():
            continue
        try:
            manifest = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for key, value in manifest.items():
            if _looks_like_version_floor(key):
                declared[f"{relative}:{key}"] = str(value)[:80]
    return {
        "declared": declared,
        "has_floor": bool(declared),
        "notes": ([] if declared else [{
            "kind": "NO_DECLARED_HOST_VERSION_FLOOR",
            "detail": "no manifest names a minimum host version; compatibility is "
                      "what was measured on real hosts, not a promise",
            "path": "",
        }]),
    }


def audit_launcher_portability(root: Path) -> dict:
    """Which shipped entry mechanism works on which OS family, as data.

    A host config is written once and read on whatever OS the operator has, so
    "the source tree is POSIX-only" has to be a reported property rather than
    something a reader infers from a `sh` in the file.
    """
    findings: list[dict] = []
    notes: list[dict] = []
    launcher = root / "scripts" / OS_NEUTRAL_LAUNCHER
    if not launcher.is_file():
        findings.append(_finding("OS_NEUTRAL_LAUNCHER_MISSING", OS_NEUTRAL_LAUNCHER,
                                 "scripts/"))
    else:
        shebang = launcher.read_text(encoding="utf-8", errors="replace").splitlines()[0]
        if not shebang.startswith("#!") or "python" not in shebang:
            findings.append(_finding("OS_NEUTRAL_LAUNCHER_NOT_PYTHON", shebang[:60],
                                     f"scripts/{OS_NEUTRAL_LAUNCHER}"))
    posix_only: list[str] = []
    for relative in MCP_CONFIGS:
        path = root / relative
        if not path.is_file():
            continue
        try:
            servers = (json.loads(path.read_text(encoding="utf-8")).get("mcpServers") or {})
        except (OSError, ValueError):
            continue
        for server in servers.values():
            command = str(server.get("command", ""))
            args = [str(a) for a in (server.get("args") or [])]
            if command in POSIX_ONLY_COMMANDS or any(a.endswith(".sh") for a in args):
                posix_only.append(relative)
                break
    if posix_only:
        notes.append(_finding(
            "SOURCE_CONFIG_IS_POSIX_ONLY",
            f"{','.join(sorted(set(posix_only)))}: needs a POSIX shell on the host",
            "scripts/"))
    return {
        "ok": not findings,
        "findings": findings,
        "notes": notes,
        "os_neutral_launcher": str(launcher.relative_to(root)) if launcher.is_file() else None,
        "configs_needing_a_shell": sorted(set(posix_only)),
        "windows_plan": {
            "entry": f"<bare host Python> {OS_NEUTRAL_LAUNCHER} scripts/research_mcp.py",
            "supported_path": "Codex's installer config uses a bare Python command and "
                              "passes the private venv path to the stdlib launcher",
            "reason_no_single_command": "Codex plugin commands must be bare or contained; "
                                        "the installer requires python/python3 or py on PATH",
            "verified_on_windows": False,
            "device_result": "NOT_TESTED_NO_WINDOWS_DEVICE_AUTHORIZED",
        },
    }


def run(root: Path, *, python: str | None = None, entry: str = "research_mcp.py",
        data_root: Path | None = None, wire: bool = True,
        artifact: str = "source") -> dict:
    """Full probe. ``wire=False`` keeps it to the static audits.

    ``artifact`` names which thing is under audit, because the two have different
    Windows contracts:

    * ``"source"`` — the checkout. Its `.mcp.json` deliberately declares the POSIX
      launcher; a POSIX-only entry here is the documented design, not a defect.
    * ``"installed"`` — the tree `setup_clients.py` produces. This is the artifact
      a Windows customer actually loads, so any shell dependency in it is a
      failure.

    Neither value makes a claim about a real Windows device: no Windows device is
    authorized for this wave, so the device result is always NOT_TESTED.
    """
    if artifact not in ("source", "installed"):
        raise ValueError("artifact must be 'source' or 'installed'")
    report: dict = {"plugin_root": str(root), "artifact": artifact}
    static = audit_plugin_tree(root)
    report["manifests_and_configs"] = static
    report["skills"] = audit_skills(root)
    shell_findings: list[dict] = []
    for relative in MCP_CONFIGS:
        path = root / relative
        if path.is_file():
            shell_findings.extend(audit_windows_config(path)["findings"])
    if artifact == "installed":
        windows_ok = not shell_findings
        documented = None
    else:
        windows_ok = True
        documented = ("SOURCE_CHECKOUT_IS_POSIX_ONLY: the Windows artifact is the tree "
                      "setup_clients.py generates, audited with artifact='installed'")
    report["windows_shape"] = {
        "ok": windows_ok,
        "findings": shell_findings,
        "documented_source_posix_launcher": documented,
        "device_result": "NOT_TESTED_NO_WINDOWS_DEVICE_AUTHORIZED",
    }
    portability = audit_launcher_portability(root)
    report["launcher_portability"] = portability
    report["host_version_floor"] = audit_host_version_floor(root)
    report["wire"] = None
    if wire:
        interpreter = python or sys.executable
        target = data_root or Path(os.environ.get("TMPDIR", "/tmp")) / "marketops-probe-store"
        report["wire"] = probe_stdio_tools(interpreter, root / "scripts" / entry,
                                           data_root=target)
        report["wire"]["interpreter"] = interpreter
    static_ok = (static["ok"] and report["skills"]["ok"]
                 and report["windows_shape"]["ok"] and portability["ok"])
    report["ok"] = bool(static_ok and (report["wire"] is None or report["wire"]["ok"]))
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--plugin-root", type=Path, required=True)
    parser.add_argument("--python", default=None, help="interpreter that has the mcp package")
    parser.add_argument("--entry", default="research_mcp.py",
                        help="the managed entrypoint the client configs declare")
    parser.add_argument("--artifact", choices=("source", "installed"), default="source",
                        help="which tree's Windows contract to judge (see run())")
    parser.add_argument("--no-wire", action="store_true",
                        help="static audits only (no mcp package required)")
    parser.add_argument("--installed-dest", type=Path, default=None,
                        help="also audit one install destination across all three hosts")
    args = parser.parse_args()
    report = run(args.plugin_root.resolve(), python=args.python, entry=args.entry,
                 wire=not args.no_wire, artifact=args.artifact)
    if args.installed_dest is not None:
        report["client_packages"] = audit_client_packages(args.installed_dest)
        report["ok"] = bool(report["ok"] and report["client_packages"]["ok"])
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
